#pragma once

#include <cstdint>
#include <memory>
#include <optional>
#include <string>
#include <string_view>
#include <vector>

#include "aion/commons/database/ConnectionProperties.h"
#include "aion/commons/database/DatabaseMetaData.h"
#include "aion/commons/database/SQLException.h"
#include "aion/commons/database/Savepoint.h"

struct st_mysql; // MYSQL of MariaDB Connector/C

namespace aion::commons::database {

class PreparedStatement;

/**
 * Java: java.sql.Connection (Connector/J ConnectionImpl), one physical connection to a MariaDB/MySQL server over MariaDB Connector/C.
 * Connections are normally obtained from DatabaseFactory::getConnection(), which returns them to the pool when the handle is destroyed.
 * <p>
 * Session setup like Connector/J: utf8mb4 character set, "found rows" instead of changed rows as UPDATE count (unless useAffectedRows=true),
 * STRICT_TRANS_TABLES added to sql_mode if missing (jdbcCompliantTruncation), auto-commit enabled.
 * <p>
 * <b>Thread safety:</b> like a JDBC connection, a Connection and its statements must only be used by one thread at a time. Handing it to
 * another thread in between (e.g. via the pool) is fine.
 * <p>
 * Statements created by a connection are closed when the connection is returned to the pool or destroyed (HikariCP closes tracked statements
 * the same way); using them afterwards throws SQLException. ResultSets are fully buffered and remain usable.
 */
class Connection {
public:
	/**
	 * Opens a new physical connection.
	 * @throws SQLException if the connection cannot be established or the session cannot be initialized
	 */
	static std::unique_ptr<Connection> open(const ConnectionProperties& properties);

	~Connection();
	Connection(const Connection&) = delete;
	Connection& operator=(const Connection&) = delete;

	/** Java: prepareStatement(sql) - a forward-only, read-only statement without generated keys */
	std::unique_ptr<PreparedStatement> prepareStatement(std::string_view sql);

	/** Java: prepareStatement(sql, autoGeneratedKeys) - Statement::RETURN_GENERATED_KEYS or Statement::NO_GENERATED_KEYS */
	std::unique_ptr<PreparedStatement> prepareStatement(std::string_view sql, int32_t autoGeneratedKeys);

	/**
	 * Java: prepareStatement(sql, resultSetType, resultSetConcurrency). ResultSet::TYPE_SCROLL_INSENSITIVE and TYPE_SCROLL_SENSITIVE both give
	 * scrollable result sets; ResultSet::CONCUR_UPDATABLE is not supported and throws.
	 */
	std::unique_ptr<PreparedStatement> prepareStatement(std::string_view sql, int32_t resultSetType, int32_t resultSetConcurrency);

	/**
	 * Java: prepareCall(sql) for "CALL proc(?, ...)" with IN parameters only. The first result set of the procedure is returned by
	 * executeQuery(); OUT parameters are not supported.
	 */
	std::unique_ptr<PreparedStatement> prepareCall(std::string_view sql);

	/** Java: setAutoCommit. Enabling auto-commit commits an open transaction (server behaviour). */
	void setAutoCommit(bool autoCommit);
	/** @return the auto-commit state as reported by the server with the last response */
	bool getAutoCommit() const noexcept;
	/** @throws SQLException "Can't call commit when autocommit=true" in auto-commit mode */
	void commit();
	/** @throws SQLException "Can't call rollback when autocommit=true" in auto-commit mode */
	void rollback();
	/** Java: setSavepoint() - an unnamed savepoint with a generated name */
	Savepoint setSavepoint();
	Savepoint setSavepoint(std::string_view name);
	void rollback(const Savepoint& savepoint);
	void releaseSavepoint(const Savepoint& savepoint);

	/**
	 * Java: isValid(timeout). Pings the server; a failed ping marks the connection broken.
	 * @param timeoutSeconds maximum time to wait for each network read or write of the ping (implemented as socket timeouts), 0 = no timeout
	 * (waits are only bounded by socketTimeout)
	 * @return true if the server responded to the ping
	 * @throws SQLException if timeoutSeconds is negative
	 */
	bool isValid(int32_t timeoutSeconds = 0);

	/** @return true if a communication failure made the connection unusable */
	bool isClosed() const noexcept { return broken; }

	/** Java: getCatalog() - the current database, or nullopt if none is selected */
	std::optional<std::string> getCatalog();

	/** Java: getMetaData() */
	DatabaseMetaData getMetaData() { return DatabaseMetaData(*this); }

	const ConnectionProperties& getProperties() const noexcept { return properties; }

	/** @return the server version string, e.g. "11.4.2-MariaDB" */
	std::string getServerVersion() const;

	/** @return true if the last server response reported an active transaction (SERVER_STATUS_IN_TRANS) */
	bool isInTransaction() const noexcept;

	/** Closes all statements created by this connection that are still open (done by the pool when the connection is returned). */
	void closeOpenStatements() noexcept;
	size_t getOpenStatementCount() const noexcept { return openStatements.size(); }

	/**
	 * Executes a statement via the text protocol, discarding any results (used for session and transaction commands).
	 * @throws SQLException on errors
	 */
	void executeSimple(std::string_view sql);

private:
	friend class PreparedStatement;

	explicit Connection(ConnectionProperties properties);

	/** opens a connection to one resolved address of properties.host */
	static std::unique_ptr<Connection> open(const ConnectionProperties& properties, const std::string& hostAddress);

	/** creates the exception for a client library error; communication errors get SQLSTATE 08S01 like Connector/J */
	static SQLException createException(unsigned int errorNumber, std::string_view sqlState, std::string_view message);
	/** throws the error of the connection handle as SQLException, marking the connection broken on communication errors */
	[[noreturn]] void throwError();
	void checkOpen() const;
	void onError(unsigned int errorNumber, std::string_view sqlState) noexcept;
	std::vector<std::optional<std::string>> querySingleRow(std::string_view sql);

	struct TextResult {
		/** update count of the first result, -1 if it was a result set */
		int64_t updateCount = -1;
		/** LAST_INSERT_ID of the first result, 0 if none */
		uint64_t insertId = 0;
	};
	/** executes a statement via the text protocol, discarding result sets */
	TextResult executeText(std::string_view sql);
	void initializeSession();
	void registerStatement(PreparedStatement* statement);
	void unregisterStatement(PreparedStatement* statement) noexcept;

	ConnectionProperties properties;
	st_mysql* mysql = nullptr;
	uint64_t autoIncrementIncrement = 1;
	bool broken = false;
	std::vector<PreparedStatement*> openStatements;
};

} // namespace aion::commons::database
