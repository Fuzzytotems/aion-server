/** one addSkill or removeSkill of an m5e-progression step */
struct LearnEvent {
	bool remove = false;
	int32_t skillId = 0;
	int32_t level = 0;
	std::optional<int32_t> messageId;
	bool passive = false;
};

/** one step of oracle.py m5e-progression */
struct ProgressionStep {
	std::string step;
	int32_t level = 0;
	std::string playerClass;
	int32_t classId = 0;
	bool daeva = false;
	std::optional<bool> accepted;
	std::string message;
	std::optional<int32_t> dialogActionId;
	std::vector<LearnEvent> events;
	int32_t baseMaxHp = 0, baseMaxMp = 0;
	std::map<int32_t, int32_t> skills;

	std::vector<LearnEvent> adds() const {
		std::vector<LearnEvent> result;
		for (const LearnEvent& event : events)
			if (!event.remove)
				result.push_back(event);
		return result;
	}
};

struct ProgressionSkill {
	int32_t skillId = 0;
	bool accepted = false;
	std::vector<std::string> refusals;
	std::vector<int32_t> launches;
	int32_t dpUse = 0;
	std::string tslot;
	json charge;
	json effects;
};

struct ProgressionAnswer {
	std::map<int32_t, int64_t> startExp;
	int32_t classChangePage = 0;
	int32_t ascensionQuest = 0;
	std::map<std::string, int32_t> actionOfClass;
	int32_t trainerNpc = 0, trainerPage = 0, trainerQuest = 0, trainerVar = 0;
	std::vector<ProgressionStep> steps;
	std::map<int32_t, ProgressionSkill> skills;
	std::map<int32_t, json> launched;
	std::map<int32_t, json> weapons;
	std::vector<json> stigmas;

	const ProgressionStep& step(std::string_view name) const {
		for (const ProgressionStep& s : steps)
			if (s.step == name)
				return s;
		throw std::runtime_error("the oracle has no step " + std::string(name));
	}
};

ProgressionAnswer parseProgression(const std::string& text) {
	const json root = json::parse(text);
	ProgressionAnswer answer;
	for (const auto& [level, exp] : root.at("experience").at("startExp").items())
		answer.startExp[std::stoi(level)] = exp.get<int64_t>();
	const json& change = root.at("classChange");
	answer.classChangePage = change.at("pageId").is_number() ? change.at("pageId").get<int32_t>() : 0;
	answer.ascensionQuest = change.at("questId").get<int32_t>();
	for (const json& choice : change.at("choices"))
		answer.actionOfClass[choice.at("playerClass").get<std::string>()] = choice.at("dialogActionId").get<int32_t>();
	const json& trainer = root.at("trainer");
	answer.trainerNpc = trainer.value("npcId", 0);
	answer.trainerPage = trainer.value("page", 0);
	answer.trainerQuest = trainer.value("questId", 0);
	answer.trainerVar = trainer.value("questVar", 0);
	for (const json& s : root.at("steps")) {
		ProgressionStep step;
		step.step = s.at("step").get<std::string>();
		step.level = s.at("level").get<int32_t>();
		step.playerClass = s.at("playerClass").get<std::string>();
		step.classId = s.at("classId").get<int32_t>();
		step.daeva = s.at("daeva").get<bool>();
		if (s.contains("accepted"))
			step.accepted = s.at("accepted").get<bool>();
		if (s.contains("message") && s.at("message").is_string())
			step.message = s.at("message").get<std::string>();
		if (s.contains("dialogActionId"))
			step.dialogActionId = s.at("dialogActionId").get<int32_t>();
		for (const json& e : s.at("events")) {
			LearnEvent event;
			event.remove = e.at("op").get<std::string>() == "remove";
			event.skillId = e.at("skillId").get<int32_t>();
			event.level = e.at("level").get<int32_t>();
			if (e.contains("messageId") && e.at("messageId").is_number())
				event.messageId = e.at("messageId").get<int32_t>();
			event.passive = e.value("passive", false);
			step.events.push_back(event);
		}
		step.baseMaxHp = s.at("baseStats").at("maxHp").get<int32_t>();
		step.baseMaxMp = s.at("baseStats").at("maxMp").get<int32_t>();
		for (const json& k : s.at("skills"))
			step.skills[k.at("skillId").get<int32_t>()] = k.at("level").get<int32_t>();
		answer.steps.push_back(std::move(step));
	}
	for (const json& s : root.at("skills")) {
		ProgressionSkill skill;
		skill.skillId = s.at("skillId").get<int32_t>();
		skill.accepted = s.at("accepted").get<bool>();
		for (const json& r : s.at("refusals"))
			skill.refusals.push_back(r.get<std::string>());
		for (const json& l : s.at("launches"))
			skill.launches.push_back(l.at("skillId").get<int32_t>());
		if (s.at("costs").contains("dpuse"))
			skill.dpUse = s.at("costs").at("dpuse").at("value").get<int32_t>();
		skill.tslot = s.value("tslot", std::string());
		if (s.contains("charge"))
			skill.charge = s.at("charge");
		skill.effects = s.at("effects");
		answer.skills[skill.skillId] = skill;
	}
	for (const auto& [id, launched] : root.at("launched").items())
		answer.launched[std::stoi(id)] = launched;
	for (const json& w : root.at("weapons"))
		answer.weapons[w.at("itemId").get<int32_t>()] = w;
	if (root.contains("stigmas"))
		for (const json& s : root.at("stigmas"))
			answer.stigmas.push_back(s);
	return answer;
}

