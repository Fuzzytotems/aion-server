#pragma once

#include "aion/gameserver/runtime/sched/PinnedCallback.h"
#include "aion/gameserver/model/gameobjects/Persistable_PersistentState.h"
#include "aion/gameserver/model/gameobjects/fwd.h"

namespace aion::gameserver::model::gameobjects {

/**
 * Objects whose database row follows a PersistentState (items, quest states, skills, houses, ...).
 * <p>
 * Hub header (docs/design/hub-headers.md, reference implementation of a Java interface): an abstract class without data members and without a
 * runtime base, inherited publicly next to the implementor's class base. The static predicates are immortal constants built by newPredicate
 * during static initialization, so newPredicate is ported (a static initializer must not reach AION_UNPORTED).
 *
 * @author Neon
 */
class Persistable {
public:
	using PersistentState = Persistable_PersistentState; // generated by xmlgen

	/** Java: Predicate<Persistable> NEW = newPredicate(PersistentState.NEW) */
	static const runtime::PinnedCallback<bool(Persistable&)> NEW;
	/** Java: Predicate<Persistable> CHANGED = newPredicate(PersistentState.UPDATE_REQUIRED) */
	static const runtime::PinnedCallback<bool(Persistable&)> CHANGED;
	/** Java: Predicate<Persistable> DELETED = newPredicate(PersistentState.DELETED) */
	static const runtime::PinnedCallback<bool(Persistable&)> DELETED;

	virtual PersistentState getPersistentState() = 0;

	virtual void setPersistentState(PersistentState state) = 0;

	/**
	 * @return Predicate that matches all Persistables with the given state. (Java also rejects null; the C++ argument is a reference, the
	 *         collections it filters hold no nulls.)
	 */
	static runtime::PinnedCallback<bool(Persistable&)> newPredicate(PersistentState state);

	virtual ~Persistable() = default;

protected:
	Persistable() = default;
	Persistable(const Persistable&) = default;
	Persistable& operator=(const Persistable&) = default;
};

} // namespace aion::gameserver::model::gameobjects
