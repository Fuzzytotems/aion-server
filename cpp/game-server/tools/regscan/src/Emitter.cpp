const std::vector<std::string>& registryNames() {
	static const std::vector<std::string> NAMES{"ai", "instance", "zone", "quest", "commands", "clientpackets", "npcids"};
	return NAMES;
}

std::vector<GeneratedFile> generateFiles(const RegistryModel& model) {
	std::vector<GeneratedFile> files;
	for (bool empty : {false, true}) {
		std::string suffix = empty ? ".empty.gen.cpp" : ".gen.cpp";
		files.push_back({"Registry.ai" + suffix, table(model, spec("ai"), model.ai, empty, &aiRow)});
		files.push_back({"Registry.instance" + suffix, table(model, spec("instance"), model.instances, empty, &instanceRow)});
		files.push_back({"Registry.zone" + suffix, table(model, spec("zone"), model.zones, empty, &zoneRow)});
		files.push_back({"Registry.quest" + suffix, table(model, spec("quest"), model.quests, empty, &questRow)});
		files.push_back({"Registry.commands" + suffix, table(model, spec("commands"), model.commands, empty, &commandRow)});
		files.push_back({"Registry.clientpackets" + suffix, table(model, spec("clientpackets"), model.clientPackets, empty, &clientPacketRow)});
		files.push_back({"Registry.npcids" + suffix, npcIdsTable(model, empty)});
	}
	files.push_back({"registry_report.txt", generateReport(model)});
	return files;
}

std::string generateReport(const RegistryModel& model) {
	std::ostringstream out;
	out << "# aion_gs_regscan registry report (generated, do not edit)\n";
	out << "# ported: C++ registrations; java: registrations of the Java handlers (- without Java input); missing: Java keys without a C++ marker;\n";
	out << "# unknownToJava: C++ keys whose Java class does not exist at the mirrored path\n\n";
	out << "files";
	for (const auto& [category, count] : model.filesPerCategory)
		out << '\t' << category << '=' << count;
	if (model.filesPerCategory.empty())
		out << "\t(none)";
	out << "\n\n";
	out << "registry\tported\tjava\tmissing\tunknownToJava\n";
	for (const ReportSection& section : model.report) {
		out << section.title << '\t' << section.ported << '\t' << countCell(section.java) << '\t'
			<< (section.java ? std::to_string(section.missing.size()) : "-") << '\t' << section.unknownToJava.size() << '\n';
	}
	for (const ReportSection& section : model.report) {
		if (!section.missing.empty()) {
			out << "\n## " << section.title << ": missing (" << section.missing.size() << ")\n";
			for (const std::string& line : section.missing)
				out << line << '\n';
		}
		if (!section.unknownToJava.empty()) {
			out << "\n## " << section.title << ": unknown to Java (" << section.unknownToJava.size() << ")\n";
			for (const std::string& line : section.unknownToJava)
				out << line << '\n';
		}
	}
	return out.str();
}

std::string summaryLine(const RegistryModel& model) {
	std::string line;
	for (const ReportSection& section : model.report) {
		if (!line.empty())
			line += ", ";
		line += section.title + " " + std::to_string(section.ported) + "/" + countCell(section.java);
	}
	return line;
}

bool writeIfChanged(const std::filesystem::path& path, const std::string& content) {
	{
		std::ifstream in(path, std::ios::binary);
		if (in) {
			std::ostringstream existing;
			existing << in.rdbuf();
			if (existing.str() == content)
				return false;
		}
	}
	if (path.has_parent_path())
		std::filesystem::create_directories(path.parent_path());
	std::ofstream out(path, std::ios::binary | std::ios::trunc);
	if (!out)
		throw std::runtime_error("cannot write " + path.string());
	out << content;
	out.close();
	if (!out)
		throw std::runtime_error("cannot write " + path.string());
	return true;
}

