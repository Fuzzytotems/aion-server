HELPER_KINDS = ('taken', 'standIn', 'stale', 'inherited', 'own')


def finalize(jfiles, index):
    """Runs after every Java file is matched. (1) Marks the C++ entities some Java body matched. (2) A definition with AION_UNPORTED or
    AION_PARTIAL that no Java body maps to is a helper; a mapped definition of the same file that calls it (directly or through another
    unmapped function, 3 levels) becomes unported (the helper is only a stub) or partial, and the helper is 'taken'. (3) Re-derives the
    statuses from the entities. (4) Classifies the helper sites nobody took: 'standIn' (its doc comment cites a Java method: that body
    counts in its own chunk), 'stale' (a stand-in whose Java method is ported now: rewire the caller), 'inherited' (a C++-only override of a
    mapped base-class function: the base's Java body counts), 'own' (the rest, counted open in the chunk that holds the file).
    Returns {rel: Counter(helper kind -> sites)}."""
    java_index = defaultdict(list)
    named = []
    for jf in jfiles:
        for jt in jf.types:
            java_index['<types>'].append(jt.path[-1])
            for m in jt.methods + jt.abstract:
                named.append(m)
                java_index[(jt.path[-1], m.name)].append(m)
    java_index['<types>'] = frozenset(java_index['<types>'])
    for m in named:
        if m.entity is not None:
            m.entity.mapped = True

    def mapped(f):
        return any(e.mapped for e in f.entities)

    for rel, fs in index.func_file.items():
        tainted = {}
        for f in fs:
            if (f.unported or f.partial) and not mapped(f):
                tainted[f.name] = 'unported' if f.stub else 'partial'
        if not tainted:
            continue
        helpers = dict(tainted)
        for _ in range(3):
            grew = False
            for f in fs:
                if f.name in tainted or mapped(f) or not f.calls:
                    continue
                if f.calls & tainted.keys():
                    tainted[f.name] = 'partial'
                    grew = True
            if not grew:
                break
        taken = set()
        for f in fs:
            if not f.calls or not mapped(f):
                continue
            hit = [n for n in f.calls if n in tainted and n != f.name]
            if not hit:
                continue
            level = 'unported' if any(tainted[n] == 'unported' for n in hit if n in helpers) and not f.partial else 'partial'
            for e in f.entities:
                if e.propagated != 'unported':
                    e.propagated = level
            taken.update(hit)
        for f in fs:
            if (f.unported or f.partial) and not mapped(f) and f.name in taken:
                f.helper = 'taken'
    for m in named:
        e = m.entity
        if e is None:
            continue
        st = e.status()
        if m.via == 'standIn':
            m.status = 'standIn' if st == 'ported' else st
        else:
            m.status = st
    by_name = defaultdict(list)
    for p in index.scopes:
        by_name[p[-1]].append(p)
    out = defaultdict(Counter)
    for rel, fs in index.func_file.items():
        for f in fs:
            n = f.unported + f.partial
            if not n or mapped(f):
                continue
            if not f.helper:
                f.helper = helper_kind(f, index, java_index, by_name)
            out[rel][f.helper] += n
    return out


def helper_kind(f, index, java_index, by_name):
    cites = [c for x in f.entities for g in x.funcs for c in g.cites if c[3] == 'doc'] or [c for c in f.cites if c[3] == 'doc']
    targets = [m for cp, name, arity, kind, standin in cites if cp for m in java_index.get((cp[-1], name), ())]
    if targets:
        return 'stale' if all(m.status in ('ported', 'standIn', 'field', 'trivial') for m in targets) else 'standIn'
    # a stand-in for a Java class's API whose method is inherited (`Java: TeamMoveUpdater.getInstance().add(player)`)
    if any(standin or (cp and cp != ('?',) and cp[-1] in java_index.get('<types>', ())) for cp, name, arity, kind, standin in cites):
        return 'standIn'
    sc = index.scopes.get(f.scope)
    seen = set()
    frontier = [sc] if sc is not None and sc.kind in ('class', 'struct') else []
    for _ in range(3):
        nxt = []
        for s in frontier:
            for b in set(_WORD.findall(s.bases)):
                for p in by_name.get(b, ()):
                    if p in seen or p == f.scope:
                        continue
                    seen.add(p)
                    if any(e.mapped for e in index.entities.get(p, {}).get(f.name, ())):
                        return 'inherited'
                    if p in index.scopes:
                        nxt.append(index.scopes[p])
        frontier = nxt
    return 'own'


