_CPP_TOKEN = re.compile(r"[A-Za-z_]\w*|\d(?:[\w.]|'(?=\w))*|::|->|\.\.\.|[^\s\w]")
_DIRECTIVE = re.compile(r'\s*#\s*([a-z]+)')
_MEMBER_BLOCK_INCLUDE = re.compile(r'\s*#\s*include\s*"([^"]+\.(?:xml\.inc|gen\.h))"')
_OPEN = {'(': ')', '[': ']', '{': '}'}
_CLOSE = {')': '(', ']': '[', '}': '{'}
CPP_KEYWORDS = skeleton.CPP_KEYWORDS
NOT_FUNCTION_NAMES = CPP_KEYWORDS | frozenset(('__declspec', '__attribute__', 'defined', '__has_include'))
QUALIFIERS = frozenset(('const', 'volatile', '&', '&&', 'override', 'final', 'mutable', 'constexpr', 'consteval'))
ACCESS = frozenset(('public', 'protected', 'private'))
MEMBER_BLOCK_MARK = 'Member block of'
_MACRO_NAME = re.compile(r'[A-Z][A-Z0-9_]*\Z')
_PREFIXED_CHAR = re.compile(r"(?<![\w'])(?:u8|u|U|L)'(?:[^'\\\n]|\\.)+'")
_WORD = re.compile(r'[A-Za-z_]\w*')


def is_ident(t):
    c = t[0]
    return c.isalpha() or c == '_'


_PARAM_DROP = frozenset(('const', 'volatile', '&', '&&', '*', 'struct', 'class', 'typename', 'enum', 'signed', 'unsigned', 'register'))


def norm_param(toks):
    """the type of one C++ parameter (its tokens) without the default argument, the name, cv/ref/pointer and namespace qualifiers:
    `const std::vector<int32_t>& ids = {}` -> 'vector<int32_t>', `Foo::Mode mode` -> 'Mode'"""
    out = []
    depth = 0
    for t in toks:
        if t in _OPEN:
            depth += 1
        elif t in _CLOSE:
            depth -= 1
        elif t == '=' and depth == 0:
            break
        out.append(t)
    out = [t for t in out if t not in _PARAM_DROP]
    if len(out) >= 2 and out[0] == '[' and out[1] == '[':      # [[maybe_unused]]
        k = next((x for x in range(2, len(out) - 1) if out[x] == ']' and out[x + 1] == ']'), None)
        if k is not None:
            out = out[k + 2:]
    if len(out) >= 2 and is_ident(out[-1]) and (is_ident(out[-2]) or out[-2] in ('>', ']')):
        out = out[:-1]
    res = []
    k = 0
    while k < len(out):
        if k + 1 < len(out) and out[k + 1] == '::' and is_ident(out[k]):
            k += 2
            continue
        if out[k] != '::':
            res.append(out[k])
        k += 1
    return ''.join(res)


def preprocess_cpp(text):
    """(code, splices): the text with the #else/#elif branches, the conditional directives, comments, literals and the other directives
    blanked (newlines kept, so token lines are source lines), and each member-block include (`#include "X.xml.inc"` / `"X.gen.h"`) replaced
    by a marker `__census_splice_<n>__`; splices maps a marker to its include path. The first branch of every #if is kept: the
    __has_include guards of the port put the real code there."""
    out = []
    stack = []            # per #if level: 'on' (first branch), 'off' (a later branch), 'dead' (inside a dropped region)
    splices = {}
    cont = False
    for line in text.split('\n'):
        if cont:
            cont = line.endswith('\\')
            out.append('')
            continue
        active = all(s == 'on' for s in stack)
        m = _DIRECTIVE.match(line)
        if m:
            d = m.group(1)
            cont = line.endswith('\\')
            if d in ('if', 'ifdef', 'ifndef'):
                stack.append('on' if active else 'dead')
                out.append('')
                continue
            if d in ('elif', 'else', 'elifdef', 'elifndef'):
                if stack and stack[-1] == 'on':
                    stack[-1] = 'off'
                out.append('')
                continue
            if d == 'endif':
                if stack:
                    stack.pop()
                out.append('')
                continue
            inc = _MEMBER_BLOCK_INCLUDE.match(line) if active else None
            if inc:
                marker = f'__census_splice_{len(splices)}__'
                splices[marker] = inc.group(1)
                out.append(marker)
                continue
            out.append(line if active else '')
            continue
        out.append(line if active else '')
    # skeleton._strip_cpp only knows a char literal whose quote follows no identifier character: blank u'x', U'x', L'x', u8'x' first
    # (else `c != u' ')` opens a bogus literal that swallows the `)`)
    code = _PREFIXED_CHAR.sub(lambda m: ' ' * len(m.group(0)), '\n'.join(out))
    return skeleton._strip_cpp(code), splices


def tokenize_cpp(code):
    T, L = [], []
    for ln, line in enumerate(code.split('\n'), 1):
        if line and not line.isspace():
            for tok in _CPP_TOKEN.findall(line):
                T.append(tok)
                L.append(ln)
    return T, L


def load_cpp_tokens(text, resolve):
    """(tokens, lines, origins): member blocks are tokenized in place of their #include (origin: the include path, line: the line of the
    #include; None for the file's own tokens). resolve(include path) -> text of a member block, or None to drop the include."""
    code, splices = preprocess_cpp(text)
    T, L = tokenize_cpp(code)
    O = [None] * len(T)
    if not splices:
        return T, L, O
    T2, L2, O2 = [], [], []
    for t, ln in zip(T, L):
        inc = splices.get(t)
        if inc is None:
            T2.append(t)
            L2.append(ln)
            O2.append(None)
            continue
        sub = resolve(inc)
        if sub is None:
            continue
        st, _ = tokenize_cpp(preprocess_cpp(sub)[0])
        T2.extend(st)
        L2.extend([ln] * len(st))
        O2.extend([inc] * len(st))
    return T2, L2, O2


def match_brackets(T):
    """M[i] = index of the bracket matching T[i] for ( ) [ ] { }, else -1 (an unbalanced closer is ignored)"""
    M = [-1] * len(T)
    stack = []
    for i, t in enumerate(T):
        if t in _OPEN:
            stack.append(i)
        elif t in _CLOSE:
            if stack and T[stack[-1]] == _CLOSE[t]:
                j = stack.pop()
                M[i] = j
                M[j] = i
    return M


