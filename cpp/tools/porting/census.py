def java_trivial(m):
    """('empty', None) for an empty constructor, ('getter'|'setter', field name) for a trivial accessor (xmlgen's patterns), else None"""
    t = m.body.texts()
    if m.kind != 'method':
        if len(t) == 2 or t[1:-1] in (['super', '(', ')', ';'], ['this', '(', ')', ';']):
            return ('empty', None)
        return None
    rt = str(m.return_type) if m.return_type is not None else 'void'
    if not m.params and rt != 'void':
        name = None
        if len(t) == 5 and t[1] == 'return' and t[3] == ';':
            name = t[2]
        elif len(t) == 7 and t[1:4] == ['return', 'this', '.'] and t[5] == ';':
            name = t[4]
        if name and is_ident(name) and name not in ('true', 'false', 'null', 'this'):
            return ('getter', name)
    if len(m.params) == 1 and rt == 'void':
        p = m.params[0].name
        if len(t) == 8 and t[1:3] == ['this', '.'] and t[4] == '=' and t[5] == p and t[6] == ';':
            return ('setter', t[3])
        if len(t) == 6 and t[2] == '=' and t[3] == p and t[4] == ';' and t[1] != p and is_ident(t[1]):
            return ('setter', t[1])
    return None


def simple_type(t):
    """'java.util.List<Foo>[]' -> 'List'"""
    return re.sub(r'<.*>', '', t).replace('[]', '').replace('...', '').strip().rpartition('.')[2]


def assign_only(t):
    """a constructor body (tokens, braces included) whose statements only assign fields (`this.f = e;`, `f = e;`) or call super(...)"""
    inner = t[1:-1]
    if '{' in inner or '->' in inner:
        return False
    stmts, cur, depth = [], [], 0
    for x in inner:
        if x in ('(', '['):
            depth += 1
        elif x in (')', ']'):
            depth -= 1
        if x == ';' and depth == 0:
            stmts.append(cur)
            cur = []
            continue
        cur.append(x)
    if cur:
        return False
    for s in stmts:
        if s[:2] == ['super', '('] or (len(s) >= 4 and s[:2] == ['this', '.'] and is_ident(s[2]) and s[3] == '=') or \
                (len(s) >= 2 and is_ident(s[0]) and s[1] == '='):
            continue
        return False
    return True


def make_method(m, owner=None):
    kind = 'constructor' if m.kind in ('constructor', 'compact_constructor') else 'method'
    body = m.body
    jm = JMethod(m.name, len(m.params), kind, any(a.simple_name == 'Override' for a in m.annotations), 'static' in m.modifiers, m.line,
                 body.end_line - m.line + 1 if body is not None else 0, java_trivial(m) if body is not None else None,
                 params=tuple(str(p.type) + ('[]' if p.varargs else '') for p in m.params), private='private' in m.modifiers,
                 abstract=body is None)
    if kind == 'constructor' and body is not None:
        jm.copy = len(m.params) == 1 and simple_type(str(m.params[0].type)) == owner
        jm.assigns = assign_only(body.texts())
    return jm


def init_fields(td, ini):
    """the fields of td an initializer assigns or fills"""
    names = {f.name for f in td.fields}
    t = ini.body.texts()
    out = []
    for k, x in enumerate(t):
        if x in names and k + 1 < len(t) and t[k + 1] in ('=', '.', '[') and \
                (k == 0 or t[k - 1] != '.' or (k >= 2 and t[k - 2] in (td.name, 'this'))) and x not in out:
            out.append(x)
    return tuple(out)


def count_body(counts, jm):
    if jm.kind == 'constructor':
        counts['java.bodies.constructors'] += 1
    elif jm.override:
        counts['java.bodies.overrides'] += 1
    else:
        counts['java.bodies.methods'] += 1


def analyse_java(rel, cu, text):
    """JFile of a parsed compilation unit: its named types with their bodies, the anonymous/local/enum-constant bodies, class and body
    counts. Lambdas are counted once per `->` token (javasrc Lambda.arrow), anonymous classes once per body brace."""
    jf = JFile(rel, text.count('\n') + (0 if text.endswith('\n') or not text else 1))
    jf.package = cu.package
    try:
        if rel.startswith(JAVA_HANDLERS):
            jf.ns = skeleton.package_namespace(cu.package, 'handlers')
        else:
            jf.ns = skeleton.package_namespace(cu.package, 'core')
    except skeleton.SkeletonError:
        jf.ns = None
    counts = jf.counts
    arrows = set()
    seen = set()

    def scan(span, enclosing, owner):
        for lam in span.lambdas():
            arrows.add(lam.arrow)
        for ne in span.anonymous_classes():
            anon(ne.anonymous, enclosing, 'anonymous', owner)
        for lt in span.local_types():
            anon(lt, enclosing, 'local', owner)

    def members(td, jt, enclosing, owner, const_body=False):
        """bodies of td; jt is its JType (named) or None (anonymous-like, written in the named type owner)"""
        for m in td.methods:
            if m.body is None:
                if jt is not None and td.kind == 'enum':
                    jt.abstract.append(make_method(m, td.name))
                continue
            jm = make_method(m, td.name)
            count_body(counts, jm)
            if jt is not None:
                jt.methods.append(jm)
                counts['java.bodies.named'] += 1
                scan(m.body, jm, jt)
            else:
                jm.anon = True
                jm.enclosing = enclosing
                jm.owner = owner
                jm.const_body = const_body
                jf.anon_methods.append(jm)
                counts['java.bodies.anonymous'] += 1
                scan(m.body, enclosing, owner)
        for f in td.fields:
            if f.initializer is not None:
                scan(f.initializer, enclosing, owner)
        for ini in td.initializers:
            counts['java.bodies.staticInitializers' if ini.static else 'java.bodies.instanceInitializers'] += 1
            if jt is not None:
                t = ini.body.texts()
                jt.inits.append(JInit(ini.static, ini.line, ini.body.end_line - ini.line + 1, init_fields(td, ini),
                                      any(t[k] == 'values' and t[k + 1] == '(' for k in range(len(t) - 1))))
            scan(ini.body, enclosing, owner)
        for c in td.enum_constants:
            for a in c.args or []:
                scan(a, enclosing, owner)
            if c.body is not None:
                anon(c.body, enclosing, 'enumConstantBody', owner)

    def named(td, path, role):
        counts['java.classes.' + role] += 1
        jt = JType(path, td.kind, role, td.line, field_names=frozenset(f.name for f in td.fields))
        jf.types.append(jt)
        members(td, jt, None, jt)
        for nt in td.types:
            inner = nt.kind == 'class' and 'static' not in nt.modifiers and td.kind in ('class', 'enum', 'record')
            named(nt, path + (nt.name,), 'inner' if inner else 'nested')

    def anon(td, enclosing, role, owner):
        key = td.body.start
        if key in seen:
            return
        seen.add(key)
        if role == 'enumConstantBody':
            counts['java.classes.anonymous'] += 1
            counts['java.classes.enumConstantBodies'] += 1
        else:
            counts['java.classes.' + role] += 1
        members(td, None, enclosing, owner, role == 'enumConstantBody')
        for nt in td.types:
            anon(nt, enclosing, 'local', owner)

    for td in cu.types:
        named(td, (td.name,), 'top')
    counts['java.bodies.lambdas'] += len(arrows)
    return jf


