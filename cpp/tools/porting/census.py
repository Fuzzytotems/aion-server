def shard(sizes, n):
    """LPT partition of [(chunk, size)] into n shards of similar total size (each shard keeps the manifest order)"""
    order = {c: k for k, (c, _) in enumerate(sizes)}
    bins = [[0, []] for _ in range(n)]
    for c, s in sorted(sizes, key=lambda x: (-x[1], order[x[0]])):
        b = min(bins, key=lambda b: (b[0], len(b[1])))
        b[0] += s
        b[1].append(c)
    return [sorted(b[1], key=order.get) for b in bins]


