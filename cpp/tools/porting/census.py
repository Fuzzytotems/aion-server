def join_variants(path):
    """C++ spellings of a Java type path: ('A','B','C') -> A::B::C, A::B_C, A_B::C, A_B_C (as tuples)"""
    out = [(path[0],)]
    for name in path[1:]:
        nxt = []
        for v in out:
            nxt.append(v + (name,))
            nxt.append(v[:-1] + (v[-1] + '_' + name,))
        out = nxt
    return out


def cpp_names(name):
    try:
        c = skeleton.cpp_ident(name)
    except skeleton.SkeletonError:
        c = name
    return {name, c, name + '_'}


def java_stems(rel):
    """(own stems below src/ or handlers/, generated stems) of a Java file, without extension"""
    if rel.startswith(JAVA_CORE):
        stem = rel[len(JAVA_CORE):-len('.java')]
        return [CPP_CORE + stem], [CPP_GENERATED + stem]
    if rel.startswith(JAVA_HANDLERS):
        stem = rel[len(JAVA_HANDLERS):-len('.java')]
        return [CPP_HANDLERS + stem], []
    return [], []


def counterpart_files(rel, existing):
    own, gen = java_stems(rel)
    cands = [s + e for s in own for e in ('.h', '.cpp', '.gen.h')] + [s + e for s in gen for e in ('.h', '.xml.inc', '.xml.h')]
    cands += [s + e for s in own for e in ('Info.h', 'Info.cpp')]
    return [c for c in cands if c in existing]


def type_files(jf, jt, existing):
    """C++ files that may define a type: the Java file's own files plus Outer_Inner.h / Outer_InnerInfo.h spellings of nested types"""
    files = list(jf.cpp_files)
    own, gen = java_stems(jf.rel)
    for v in join_variants(jt.path):
        if len(v) == 1 and v[0] != jt.path[0]:
            for s in own + gen:
                d = s.rpartition('/')[0]
                for f in (f'{d}/{v[0]}.h', f'{d}/{v[0]}.cpp', f'{d}/{v[0]}Info.h', f'{d}/{v[0]}.xml.inc'):
                    if f in existing and f not in files:
                        files.append(f)
    return files


def arity_ok(e, a, extra, ctor):
    lo, hi = e.min_arity, e.max_arity
    if ctor and e.createkey:
        lo, hi = lo - 1, hi - 1
    return lo <= a <= hi or (extra and lo <= a + 1 <= hi)


