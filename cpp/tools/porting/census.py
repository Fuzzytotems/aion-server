def cpp_type_names(c):
    """base names of a normalized C++ parameter type: 'Ref<Player>' -> {'Ref', 'Player'}"""
    base = c.split('<', 1)[0]
    out = {base}
    if base in _CPP_WRAPPERS and '<' in c:
        out.add(c[c.index('<') + 1:].split('<', 1)[0].split(',', 1)[0].rstrip('>'))
    return out


def cpp_template_arg(c):
    """the first template argument of a normalized C++ type ('span<float>' -> 'float'), or None"""
    if '<' not in c or '>' not in c:
        return None
    inner = c[c.index('<') + 1:c.rindex('>')]
    depth = 0
    for i, ch in enumerate(inner):
        if ch == '<':
            depth += 1
        elif ch == '>':
            depth -= 1
        elif ch == ',' and depth == 0:
            return inner[:i]
    return inner


def type_similar(j, c):
    """a Java parameter type as written and a normalized C++ parameter type that may port it"""
    names = cpp_type_names(c)
    if j.endswith('[]') or j.endswith('...'):
        elem = j[:-2] if j.endswith('[]') else j[:-3]
        if not names & _CPP_SEQUENCES:
            return 'string_view' in names and elem in ('byte', 'char')
        arg = cpp_template_arg(c)
        return arg is None or type_similar(elem, arg)
    js = simple_type(j)
    if js in _JAVA_TYPE_MAP:
        return bool(names & _JAVA_TYPE_MAP[js])
    if js in _JAVA_SEQUENCES:
        return bool(names & _CPP_SEQUENCES)
    if js in _JAVA_MAPS:
        return bool(names & _CPP_MAPS)
    return js in names


def param_score(m, e):
    """parameters of m that have a similar type at the same position of e (best alignment when e takes more)"""
    jp, cp = m.params, e.params
    if e.createkey and cp:
        cp = cp[1:]
    if not jp or not cp:
        return 0
    return max(sum(1 for a, b in zip(jp, cp[off:]) if type_similar(a, b)) for off in range(max(0, len(cp) - len(jp)) + 1))


def strip_createkey(params):
    return params[1:] if params and params[0].endswith('CreateKey') else params


def assign(m, e, via=''):
    m.status = e.status()
    m.entity = e
    m.via = via


def match_group(ms, ents, ctor, via='', differs=True):
    """ms: the unmatched Java overloads of one name; ents: [(CppEntity, extra)] with extra = 1 when the C++ function may take one more
    parameter (an enum companion, the object of a file-local helper). Per arity the overloads take distinct declarations, the best
    parameter-type match first; a declaration whose parameter range covers several arities serves one overload of each. When differs,
    the overloads left over pair with the unused declarations ("arity differs"). Sets status/entity/via; the rest keep status ''."""
    used = set()
    rest = []
    surplus = []
    by_arity = defaultdict(list)
    for m in ms:
        by_arity[m.arity].append(m)
    for a in sorted(by_arity):
        group = by_arity[a]
        cand = [k for k, (e, extra) in enumerate(ents) if arity_ok(e, a, extra, ctor)]
        if not cand:
            rest.extend(group)
            continue
        pairs = sorted(((param_score(m, ents[k][0]), -abs(ents[k][0].max_arity - a), -k, -mi, mi, k)
                        for mi, m in enumerate(group) for k in cand), reverse=True)
        tm, tk = set(), set()
        for *_, mi, k in pairs:
            if mi in tm or k in tk:
                continue
            assign(group[mi], ents[k][0], via)
            tm.add(mi)
            if ents[k][0].max_arity < 99:
                tk.add(k)            # a variadic declaration (an inheriting constructor, a parameter pack) serves every overload
            else:
                used.add(k)
        used |= tk
        for mi, m in enumerate(group):
            if mi in tm:
                continue
            # two Java overloads the port merged into one declaration (Collection<Point2D> and Point2D[] -> span<const Point2D>): every
            # parameter type of this one matches the declaration too
            full = [k for k in cand if a and param_score(m, ents[k][0]) == a]
            if full:
                assign(m, ents[full[0]][0], via or 'merged')
            else:
                surplus.append(m)
    if differs:
        unused = [k for k in range(len(ents)) if k not in used]
        for m in rest:
            if not unused:
                break
            k = min(unused, key=lambda x: (abs(ents[x][0].max_arity - m.arity), x))
            unused.remove(k)
            assign(m, ents[k][0], via)
            m.arity_differs = True
        # a same-arity overload that lost the pairing takes an unused declaration of another arity only on parameter-type evidence
        for m in surplus:
            scored = [(param_score(m, ents[k][0]), -k) for k in unused]
            if scored and max(scored)[0] > 0:
                k = -max(scored)[1]
                unused.remove(k)
                assign(m, ents[k][0], via)
                m.arity_differs = True


def namespaces_of(jf):
    if jf.ns is None:
        return []
    out = [jf.ns]
    for src, dst in NAMESPACE_ALIASES.items():
        if jf.ns[:len(src)] == src:
            out.append(dst + jf.ns[len(src):])
    return out


def java_type_name(jf, jt):
    """'services.cron.CronService.CronScheduleBuilder' (below com.aionemu.gameserver)"""
    pkg = (jf.package or '')
    pkg = pkg[len('com.aionemu.gameserver'):].lstrip('.') if pkg.startswith('com.aionemu.gameserver') else pkg
    return (pkg + '.' if pkg else '') + '.'.join(jt.path)


def replaced_reason(jf, jt):
    for prefix, tpath, reason in REPLACED:
        if jf.rel.startswith(prefix) and (tpath is None or jt.path[:len(tpath)] == tpath):
            return reason
    return None


def derived_companion_names(jt, m):
    """names the port gives an enum method written as a free function: <enum><Method>, <enum><Stem> (get/is dropped), <enum>Of for a static
    lookup, get<Enum><Stem>; <enum> is the lower-camel simple name, also without an `Enum` suffix"""
    e = jt.path[-1]
    bases = [e[0].lower() + e[1:]]
    if e.endswith('Enum') and len(e) > 4:
        bases.append(bases[0][:-4])
    up = m.name[0].upper() + m.name[1:]
    stem = None
    for p in ('get', 'is'):
        if m.name.startswith(p) and len(m.name) > len(p) and m.name[len(p)].isupper():
            stem = m.name[len(p):]
    out = set()
    for b in bases:
        out.add(b + up)
        if stem:
            out.add(b + stem)
        if m.static and m.arity == 1 and (m.name in ('get', 'of', 'valueOf', 'find') or m.name.startswith(('get', 'from', 'by', 'for'))):
            out.add(b + 'Of')
    out.add('get' + e + (stem or up))
    return out


class MatchContext:
    """what matching needs besides the Java file: the C++ index, the C++ files that exist and their owning chunks"""

    def __init__(self, index, existing, cpp_owner=None):
        self.index = index
        self.existing = existing
        self.cpp_owner = cpp_owner or {}
        self._code = {}

    def chunk_of(self, rel):
        return self.cpp_owner.get(rel)

    def code_lines(self, rel):
        """raw lines of a C++ file (for the initializer rule), or None"""
        if rel not in self._code:
            t = self.index.texts.get(rel)
            self._code[rel] = t.split('\n') if t is not None else None
        return self._code[rel]


_INIT_SUSPECT = re.compile(r'(?i)until\b[^\n]*\bported|not\s+ported|\bunported\b|AION_UNPORTED|AION_PARTIAL|\bstub\b')
_INIT_NOTE = re.compile(r"(?i)\bstatic\s+(?:initializer|HashMap|map)\b")


def match_init(ini, jt, files, ctx):
    """status of a static or instance initializer: 'unassessed' when it assigns no field of its class; else the C++ definitions of those
    fields in the class's own files decide: none -> 'undeclared', one next to an unported note (`null until X is ported`, AION_UNPORTED)
    -> 'partial', else 'ported'"""
    if not ini.fields:
        ini.status = 'unassessed'
        return
    found = None
    for rel in files:
        lines = ctx.code_lines(rel)
        if lines is None:
            continue
        for f in ini.fields:
            rx = re.compile(r'\b' + re.escape(f) + r'\w*\b')
            for k, ln in enumerate(lines):
                code = ln.split('//', 1)[0]
                if not rx.search(code):
                    continue
                found = found or f'{rel}:{k + 1}'
                if _INIT_SUSPECT.search('\n'.join(lines[max(0, k - 2):k + 1])):
                    ini.status = 'partial'
                    ini.where = f'{rel}:{k + 1}'
                    return
    if found is None:
        # the port replaced the map or table the initializer fills: an enum lookup over values() with a companion, or a comment that
        # names the initializer (`Java's static HashMap id -> ChatType is a lookup over the constexpr table`)
        noted = None
        for rel in files:
            lines = ctx.code_lines(rel) or []
            for k, ln in enumerate(lines):
                if _INIT_NOTE.search(ln):
                    near = '\n'.join(lines[max(0, k - 1):k + 2])
                    noted = (rel, k + 1, 'partial' if _INIT_SUSPECT.search(near) else 'ported')
                    break
            if noted:
                break
        if ini.lookup and jt.kind == 'enum' and jt.free_matches:
            ini.status, ini.where = 'ported', 'the enum companion replaces the lookup map'
        elif noted:
            ini.status, ini.where = noted[2], f'{noted[0]}:{noted[1]}: a comment names the static initializer'
        else:
            ini.status = 'undeclared'
    else:
        ini.status = 'ported'
        ini.where = found


def match_type(jt, jf, ctx):
    index = ctx.index
    nss = namespaces_of(jf)
    variants = join_variants(jt.path)
    scopes = []
    for ns in nss:
        for v in variants:
            s = ns + v
            if (s in index.scopes or s in index.entities) and s not in scopes:
                scopes.append(s)
    files = type_files(jf, jt, ctx.existing)
    if not scopes:
        # a class of the same trailing name in the Java file's own C++ files (another namespace, an anonymous namespace, or - for a
        # nested type - its bare name: PlayerClass.PlayerStatsTemplate is `PlayerStatsTemplate` in PlayerClassInfo.cpp)
        tails = variants + ([(jt.path[-1],)] if len(jt.path) > 1 else [])
        for f in files:
            for s in index.scopes_by_file.get(f, ()):
                if any(s[-len(v):] == v for v in tails) and s not in scopes:
                    scopes.append(s)
    if not scopes:
        # a class the port wrote under another name or in another file and marked (`// fieldmap-class: <FQCN>`, `/** Java: <FQCN> */`)
        s = index.class_alias.get(java_type_name(jf, jt))
        if s is not None:
            scopes.append(s)
    jt.scopes = scopes
    scope_files = {rel for s in scopes for rel, _ in (index.scopes[s].defs if s in index.scopes else ())}
    fields = set()
    for s in scopes:
        sc = index.scopes.get(s)
        if sc is not None:
            fields |= sc.fields
    cpp_simple = {v[-1] for v in variants}
    word = re.compile(r'\b(' + '|'.join(re.escape(n) for n in sorted(cpp_simple)) + r')\b')
    # a function of another file takes the enum only if its first parameter spells the whole type (Outer::Inner or Outer_Inner)
    strict = re.compile(r'\b(' + '|'.join(re.escape(' :: '.join(v)) for v in variants) + r')\b')
    fileset = set(files) | scope_files
    for n in cpp_simple:
        for s in java_stems(jf.rel)[0]:
            fileset.add(s.rpartition('/')[0] + f'/{n}Info.h')
    own_chunk = jf.chunk

    def same_chunk(rel):
        return rel in fileset or (own_chunk is not None and ctx.chunk_of(rel) == own_chunk)

    free_ns = defaultdict(list)
    local_ents = defaultdict(list)       # file-local helpers: namespace-scope functions of the class's own files in a sub-namespace
    for ns in nss:
        for n, es in index.entities.get(ns, {}).items():
            free_ns[n].extend(es)
        for suffix in (('<anon>',), ('detail',), ('detail', '<anon>'), ('<anon>', '<anon>')):
            for n, es in index.entities.get(ns + suffix, {}).items():
                local_ents[n].extend(e for e in es if e.files & fileset)
    comment_files = fileset | scope_files
    groups = defaultdict(list)
    for m in jt.methods + jt.abstract:
        groups[(m.kind, m.name)].append(m)
    # runtime/sched/TaskConcepts.h: a Runnable may be ported as an aggregate `struct X : TaskStruct { members; void operator()() const; }`
    task_struct = any('TaskStruct' in index.scopes[s].bases for s in scopes if s in index.scopes)
    order = sorted(groups.items(), key=lambda kv: kv[0][0] == 'constructor')     # methods first: free_matches decides enum ctors
    for (kind, name), ms in order:
        if kind == 'constructor':
            if jt.kind == 'enum':
                enum_ctor(jt, ms, scopes, fileset, jf, index)
                continue
            ents = [(e, 0) for s in scopes for e in index.entities.get(s, {}).get(s[-1], [])]
            # a create() factory with a constructor's parameters is that constructor's twin, not another overload
            sigs = {strip_createkey(e.params) for e, _ in ents}
            ents += [(e, 0) for s in scopes for e in index.entities.get(s, {}).get('create', []) if e.params not in sigs]
            match_group(ms, ents, True)
            if scopes:
                ctors = [e for e, _ in ents]
                cls = any(index.scopes[s].kind in ('class', 'struct') for s in scopes if s in index.scopes)
                for m in ms:
                    if m.status:
                        continue
                    if task_struct:
                        m.status, m.via = 'trivial', 'taskStruct'        # aggregate initialization of the task struct
                    elif m.copy and not any(e.special == 'delete' and e.max_arity == 1 for e in ctors):
                        m.status, m.via = 'trivial', 'implicitCopy'      # a value type's implicit copy constructor
                    elif m.assigns and not ctors and cls and fields:
                        m.status, m.via = 'trivial', 'aggregate'         # no constructor declared: aggregate initialization
        else:
            names = cpp_names(name)
            if name in ('run', 'call') and all(m.arity == 0 for m in ms):
                names.add('operator()')
            if name == 'iterator' and all(m.arity == 0 for m in ms):
                names.add('begin')                                        # Iterable ported as begin()/end()
            ents = [(e, 0) for s in scopes for n in names for e in index.entities.get(s, {}).get(n, [])]
            if jt.kind == 'enum' or any(m.static for m in ms):
                for n in names:
                    for e in free_ns.get(n, ()):
                        if e.member:
                            continue
                        if jt.kind == 'enum' and word.search(e.first_param):
                            ents.append((e, 1))
                            jt.free_matches = True
                        elif e.files & fileset:
                            ents.append((e, 1 if jt.kind == 'enum' else 0))
                            jt.free_matches = True
            match_group(ms, ents, False)
            left = [m for m in ms if not m.status]
            if left:
                # a private or static helper written as a file-local function of the class's own files (the object may become a parameter)
                loc = [(e, 1) for n in names for e in local_ents.get(n, ()) if not e.member]
                match_group(left, loc, False, 'fileLocal', differs=False)
                if any(m.status for m in left):
                    jt.free_matches = True
            left = [m for m in ms if not m.status]
            if left and jt.kind == 'enum':
                # an enum method written as a free function under a derived name (brokerPacketTypeId, houseDoorStateOf) in the enum's own
                # files, or as a stand-in in another chunk's file that takes the enum
                for m in left:
                    cands = []
                    for n in derived_companion_names(jt, m) | (names if not m.static else set()):
                        for e in index.free_by_name.get(n, ()):
                            own = bool(e.files & fileset)
                            if own or strict.search(e.first_param) or (n.endswith('Of') and n not in names):
                                cands.append((e, 1))
                    if cands:
                        match_group([m], cands, False, 'renamed', differs=False)
                        if m.status:
                            credit_where(m, same_chunk)
                            if m.via == 'renamed':
                                jt.free_matches = True
        for m in ms:
            if m.status:
                continue
            cite(m, jt, jf, index, fileset, same_chunk)
            if m.status:
                continue
            if m.trivial and m.trivial[0] in ('getter', 'setter') and (m.trivial[1] in fields or m.trivial[1] + '_' in fields):
                m.status = 'field'
            elif m.trivial and m.trivial[0] == 'getter' and jt.kind == 'enum' and \
                    m.trivial[1] in table_fields(index, fileset | cited_files(jt, index, same_chunk), scopes, jt.path[-1]):
                m.status, m.via = 'field', 'table'       # enum constructor data held in a C++ table struct
            elif m.trivial and m.trivial[0] == 'empty' and (scopes or jt.free_matches):
                m.status = 'trivial'
            elif m.name in omission_words(index, comment_files, kind == 'constructor') or \
                    (kind == 'constructor' and scopes and '<constructor>' in omission_words(index, comment_files, True)):
                m.status, m.where = 'omitted', 'a C++ comment of the class documents the omission'
            elif replaced_reason(jf, jt):
                m.status, m.where = 'replaced', replaced_reason(jf, jt)
            elif not scopes and not jt.free_matches and jt.path[-1] in package_omissions(index, jf):
                m.status, m.where = 'omitted', 'a C++ comment of the package documents that the class has no counterpart'
            else:
                m.status = 'undeclared'
                m.undeclared_kind = ('objectProtocol' if m.name in OBJECT_PROTOCOL else 'constructor' if kind == 'constructor'
                                     else 'override' if m.override else 'accessor' if m.trivial else 'other')
                m.mentioned = any(m.name in index.comment_words.get(f, ()) for f in comment_files)
    for ini in jt.inits:
        match_init(ini, jt, sorted(f for f in fileset if f in ctx.existing and not f.startswith(CPP_GENERATED)), ctx)


def credit_where(m, same_chunk):
    """a status credited through a function of another file: 'renamed' in the class's own files or its chunk, 'standIn' elsewhere"""
    e = m.entity
    rels = sorted(e.files) if e is not None else []
    own = [r for r in rels if same_chunk(r)]
    m.where = (own or rels or [''])[0]
    if not own:
        m.via = 'standIn'
        if m.status == 'ported':
            m.status = 'standIn'


def cite(m, jt, jf, index, fileset, same_chunk):
    """credits an unmatched Java body through a C++ citation of it (`Java: Class.method(`): a doc comment on a function (renamed, or a
    stand-in in another chunk), or - for a private method - a comment inside a function of the class's own files (inlined there)"""
    names = {m.name} if m.kind == 'method' else {jt.path[-1]}
    pkg = tuple((jf.package or '').split('.'))
    full = pkg + jt.path
    best = None
    for n in names:
        # an abstract enum method whose constant bodies the port writes as a switch: `// Java: type.write(packet, value)` in that switch
        keys = ((jt.path[-1], n), (None, n)) + ((('?', n),) if m.abstract else ())
        for key in keys:
            for f, cp, arity, kind, standin in index.citations.get(key, ()):
                if cp == ('?',):
                    whole = False
                elif cp is not None:
                    if full[-len(cp):] != cp:
                        continue
                    whole = len(cp) >= len(jt.path)
                else:
                    whole = False
                if not whole and f.rel not in fileset:
                    continue
                if arity is not None and arity != m.arity:
                    continue
                if kind == 'body' and not ((m.private or m.abstract) and f.rel in fileset):
                    continue
                if cp == ('?',) and kind != 'body':
                    continue
                if kind == 'doc' and not f.entities:
                    continue
                rank = (0 if same_chunk(f.rel) else 1, 0 if kind == 'doc' else 1, 0 if arity is not None else 1)
                if best is None or rank < best[0]:
                    best = (rank, f, kind)
    if best is None:
        return
    _, f, kind = best
    e = f.entities[0] if f.entities else None
    if e is None:
        return
    if kind == 'body':
        assign(m, e, 'inlined')
        m.where = f'{f.rel}:{f.line}'
        return
    assign(m, e, 'renamed')
    credit_where(m, same_chunk)


def cited_files(jt, index, same_chunk):
    """files of the class's chunk whose doc comments cite a method of the class (a companion under another file name), with their
    .h/.cpp siblings"""
    out = set()
    for (cls, _), lst in index.citations.items():
        if cls != jt.path[-1]:
            continue
        for f, cp, arity, kind, standin in lst:
            if kind == 'doc' and same_chunk(f.rel):
                stem = f.rel.rsplit('.', 1)[0]
                out.update((f.rel, stem + '.h', stem + '.cpp'))
    return out


_TABLE_NAME = re.compile(r'(?:Data|Entry|Info|Row|Table|Values)$')


def table_fields(index, files, scopes, enum_name=None):
    """data members of the table structs defined in files, the class's own scopes excluded (enum constructor data): a struct whose name
    contains the enum's name or ends in Data/Entry/Info/Row/Table/Values"""
    out = set()
    for rel in files:
        for p in index.scopes_by_file.get(rel, ()):
            if p in scopes or index.scopes[p].kind not in ('struct', 'class'):
                continue
            if enum_name is not None and enum_name not in p[-1] and not _TABLE_NAME.search(p[-1]):
                continue
            out |= index.scopes[p].fields
    return out


def omission_words(index, files, calls=False):
    """identifiers named in the omission comments of files (calls: only those written `name(`, for constructors: the class name alone
    appears in every class comment)"""
    src = index.omission_calls if calls else index.omission_words
    out = set()
    for rel in files:
        out |= src.get(rel, frozenset())
    return out


def package_omissions(index, jf):
    """identifiers of the omission comments of the C++ files in the Java file's package directory"""
    own, _ = java_stems(jf.rel)
    if not own:
        return frozenset()
    d = own[0].rpartition('/')[0] + '/'
    cache = index.__dict__.setdefault('_package_omissions', {})
    if d not in cache:
        out = set()
        for rel, words in index.omission_words.items():
            if rel.startswith(d) and '/' not in rel[len(d):]:
                out |= words
        cache[d] = frozenset(out)
    return cache[d]


def enum_ctor(jt, ms, scopes, fileset, jf, index):
    """an enum constructor is 'enumCtor' (its data is a C++ table) when it takes no argument, or the port has a place for the data: a
    companion (<Enum>Info.h/.cpp, a free function matched), explicit enumerator values, or a table struct in the enum's files; 'standIn'
    when its methods are stand-ins in other chunks and none is undeclared (the data sits in the stand-ins); else 'undeclared' (kind
    enumData: the data is nowhere in C++)"""
    info = any(f.endswith(('Info.h', 'Info.cpp')) for f in jf.cpp_files)
    explicit = any(index.scopes[s].explicit for s in scopes if s in index.scopes)
    stand = any(m.via == 'standIn' for m in jt.methods) and not any(m.status == 'undeclared' for m in jt.methods)
    table = bool(scopes) and bool(table_fields(index, fileset, scopes, jt.path[-1]))
    for m in ms:
        if m.arity == 0 or info or explicit or jt.free_matches or table or any(x.via == 'table' for x in jt.methods):
            m.status = 'enumCtor'
        elif stand:
            m.status, m.via = 'standIn', 'standIn'
        else:
            m.status = 'undeclared'
            m.undeclared_kind = 'enumData'


def match_file(jf, index, existing, cpp_owner=None, ctx=None):
    ctx = ctx or MatchContext(index, existing, cpp_owner)
    jf.cpp_files = counterpart_files(jf.rel, existing)
    for jt in jf.types:
        match_type(jt, jf, ctx)
    if not jf.cpp_files:
        jf.ported_elsewhere = any(jt.scopes for jt in jf.types if jt.role == 'top')
    # an enum constant body implements the enum's method of the same name (abstract or overridden)
    for am in jf.anon_methods:
        if am.const_body and am.owner is not None and am.enclosing is None:
            jt = am.owner
            am.enclosing = next((m for m in jt.methods + jt.abstract if m.name == am.name and m.arity == am.arity), None)


