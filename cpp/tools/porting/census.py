def live_checks(check):
    """the known answers of the verification round against the real tree (a full measurement, about 30 s)"""
    ms = Measure()
    by_file = {jf.rel: jf for jf in ms.jfiles}
    for rel, tpath, name, arity, line, status, via in LIVE_CHECKS:
        what = f'live {tpath}.{name}/{arity}' + (f' L{line}' if line else '')
        jf = by_file.get(JAVA_CORE + rel)
        jt = next((t for t in jf.types if '.'.join(t.path) == tpath), None) if jf else None
        found = [m for m in (jt.methods if jt else ()) if m.name == name and m.arity == arity and (line is None or m.line == line)]
        if not found:
            check(what, 'no such Java body', 'a Java body')
            continue
        for m in found:
            check(what, (m.status, m.via if via is not None else None), (status, via))
    agt = by_file.get(JAVA_CORE + 'model/autogroup/AutoGroupType.java')
    check('live AutoGroupType constant bodies of the open newAutoInstance',
          sum(1 for m in (agt.anon_methods if agt else ()) if m.const_body and m.enclosing is not None and m.enclosing.abstract
              and m.enclosing.status in OPEN_STATUSES), 33)
    for rel, tpath, want in LIVE_INITIALIZERS:
        jf = by_file.get(JAVA_CORE + rel)
        check(f'live {tpath} initializers', [i.status for jt in (jf.types if jf else ()) if '.'.join(jt.path) == tpath for i in jt.inits],
              want)
    sm = by_file.get(JAVA_CORE + 'network/aion/serverpackets/SM_SYSTEM_MESSAGE.java')
    check('live SM_SYSTEM_MESSAGE bodies not ported', sum(1 for jt in (sm.types if sm else ()) for m in jt.methods
                                                          if m.status != 'ported'), 0)
    kinds = {where.split(' ', 1)[1]: kind for _, where, kind, _ in ms.helper_list()}
    for name, kind in (('standins::followStartServiceNewFollowingToTargetCheckTask', 'stale'),
                       ('standins::playerGroupServiceRemovePlayer', 'standIn'), ('PlayerGroup::getMember', 'inherited'),
                       ('<anon>::unportedScoreBase', 'taken')):
        check(f'live helper {name}', kinds.get(name), kind)


def main(argv=None):
    ap = argparse.ArgumentParser(prog='census.py', description=__doc__.split('\n', 1)[0])
    ap.add_argument('--json', help='write the census JSON here')
    ap.add_argument('--markdown', help='write the census tables (Markdown) here')
    ap.add_argument('--chunks', type=lambda s: [x for x in s.split(',') if x], help='only these chunks in the per-chunk output')
    ap.add_argument('--no-types', action='store_true', help='leave the per-type records out of the JSON')
    ap.add_argument('--history', nargs='*', default=[], metavar='COMMIT',
                    help='also count the AION_UNPORTED sites per phase at these commits (git grep, current manifest)')
    ap.add_argument('--self-check', action='store_true',
                    help='run the built-in checks (synthetic, then the known answers against the tree) and exit')
    ap.add_argument('--no-tree', action='store_true', help='with --self-check: only the synthetic checks')
    args = ap.parse_args(argv)
    if args.self_check:
        return self_check(tree=not args.no_tree)
    doc, chunk_order, phase_of = run(args)
    if args.json:
        with open(args.json, 'w', encoding='utf-8', newline='\n') as f:
            json.dump(doc, f, indent=1, ensure_ascii=False)
            f.write('\n')
    md = markdown(doc, chunk_order, phase_of)
    if args.markdown:
        with open(args.markdown, 'w', encoding='utf-8', newline='\n') as f:
            f.write(md)
    if not args.json and not args.markdown:
        print(md)
    t = doc['totals']
    print(f"census: {doc['cppIndex']['files']} C++ files, {g(t, 'all.java.files')} Java files; phase 5: "
          f"{g(t, 'phase5.cpp.unportedSites')} AION_UNPORTED + {g(t, 'phase5.cpp.partialSites')} AION_PARTIAL sites, "
          f"{g(t, 'phase5.hidden.undeclared')} undeclared, {g(t, 'phase5.hidden.declaredOnly')} declared-only bodies "
          f"-> {g(t, 'phase5.open.bodies')} open; timing {doc['timing']}", file=sys.stderr)
    return 0


if __name__ == '__main__':
    sys.exit(main())
