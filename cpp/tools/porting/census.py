def git(*args):
    out = subprocess.run(['git', '-C', str(REPO_ROOT)] + list(args), capture_output=True)
    if out.returncode != 0:
        return None
    return out.stdout.decode('utf-8', 'replace')


def in_flux(manifest):
    """{chunk: [status path]} of the files git reports modified, added or untracked, by chunk (C++ owners, test directories, Java claims)"""
    text = git('status', '--porcelain=v1', '-z', '-uall')
    if text is None:
        return None
    flux = defaultdict(list)
    entries = text.split('\0')
    i = 0
    gs = GAME_SERVER.relative_to(REPO_ROOT).as_posix() + '/'
    js = JAVA_GAME_SERVER.relative_to(REPO_ROOT).as_posix() + '/'
    while i < len(entries):
        e = entries[i]
        i += 1
        if len(e) < 4:
            continue
        code, path = e[:2], e[3:]
        if code[0] in 'RC':
            i += 1
        names = set()
        if path.startswith(gs):
            rel = path[len(gs):]
            top = rel.split('/', 1)[0]
            if top in manifest.roots:
                owners, _ = chunkslib.owners_of(manifest, rel)
            elif top == chunkslib.TESTS:
                owners, _ = manifest.test_dir_parts(rel)
            else:
                owners, _ = manifest.other_file_parts(rel)
            names = {p.name for p in owners}
        elif path.startswith(js) and path.endswith('.java'):
            rel = path[len(js):]
            names = {p.name for p in manifest.parts if p.claims_java(rel)}
        for n in names:
            flux[n].append(f'{code.strip()} {path}')
    return {k: sorted(v) for k, v in flux.items()}


def history(manifest, commits):
    """{commit: {date, sites per phase, P5 sites per chunk}}: AION_UNPORTED( occurrences at each commit (git grep -o), attributed with the
    current manifest - how the working-tree count relates to figures measured earlier"""
    phase = {p.name: p.phase for p in manifest.parts if not p.lease}
    gs = GAME_SERVER.relative_to(REPO_ROOT).as_posix() + '/'
    out = {}
    for commit in commits:
        text = git('grep', '-o', '-e', 'AION_UNPORTED(', commit, '--', gs + 'src', gs + 'handlers')
        if text is None:
            out[commit] = {'error': 'git grep failed'}
            continue
        per_phase, per_chunk = Counter(), Counter()
        for line in text.splitlines():
            parts = line.split(':')
            if len(parts) < 3:
                continue
            owners, _ = chunkslib.owners_of(manifest, parts[1][len(gs):])
            name = owners[0].name if owners else '(unowned)'
            per_phase['phase' + phase.get(name, '?')] += 1
            per_chunk[name] += 1
        date = (git('log', '-1', '--format=%cd', '--date=iso', commit) or '').strip()
        out[commit] = {'date': date, **dict(sorted(per_phase.items())),
                       'p5Chunks': {k: v for k, v in sorted(per_chunk.items()) if phase.get(k) == '5'}}
    return out


def java_for_generated(rel, java_set, header_java=None):
    """the Java file a generated file comes from: the one its header names, else <stem>.java, else the longest '_'-prefix of the stem
    (SM_BROKER_SERVICE_BrokerPacketType -> SM_BROKER_SERVICE)"""
    if header_java and header_java in java_set:
        return header_java
    rest = rel[len(CPP_GENERATED):]
    d, _, base = rest.rpartition('/')
    parts = base.split('.', 1)[0].split('_')
    for k in range(len(parts), 0, -1):
        j = JAVA_CORE + (d + '/' if d else '') + '_'.join(parts[:k]) + '.java'
        if j in java_set:
            return j
    return None


def build_index(cpp_files, root=GAME_SERVER, log=None):
    index = CppIndex()
    cache = {}

    def read(rel):
        if rel not in cache:
            try:
                cache[rel] = (Path(root) / rel).read_text(encoding='utf-8-sig', errors='replace')
            except OSError:
                cache[rel] = None
        return cache[rel]

    def resolve(inc):
        for r in ('generated', 'src', 'handlers'):
            text = read(f'{r}/{inc}')
            if text is not None:
                return text if (inc.endswith('.xml.inc') or MEMBER_BLOCK_MARK in text[:4000]) else None
        return None

    for rel in cpp_files:
        text = read(rel)
        if text is None:
            continue
        base = rel.rpartition('/')[2]
        member_block = base.endswith('.xml.inc') or (base.endswith('.gen.h') and MEMBER_BLOCK_MARK in text[:4000])
        skip = member_block or base.endswith('.gen.inc') or '.bind.' in base
        index.parse(rel, text, resolve, parse=not skip)
    index.finish()
    return index


def new_counter():
    return Counter()


def aggregate_java(c, jf):
    """adds a JFile's measures to the Counter c"""
    c['java.files'] += 1
    c['java.lines'] += jf.lines
    if jf.error:
        c['java.parseErrors'] += 1
    for k, v in jf.counts.items():
        c[k] += v
    open_named = 0
    for jt in jf.types:
        if not jt.scopes and not jt.free_matches:
            c['hidden.typesNoScope'] += 1
            if jt.methods:
                c['hidden.typesNoScopeWithBodies'] += 1
        for m in jt.methods:
            c['status.' + m.status] += 1
            if m.via:
                c['credit.' + m.via] += 1
            if m.arity_differs:
                c['hidden.arityDiffers'] += 1
            if m.status == 'undeclared':
                c['hidden.undeclared'] += 1
                c['hidden.undeclaredByKind.' + m.undeclared_kind] += 1
                c['hidden.undeclaredJavaLines'] += m.lines
                if m.mentioned:
                    c['hidden.undeclaredMentioned'] += 1
            elif m.status == 'declaredOnly':
                c['hidden.declaredOnly'] += 1
                c['hidden.declaredOnlyJavaLines'] += m.lines
            elif m.status in ('unported', 'partial'):
                c['status.unportedJavaLines'] += m.lines
            if m.status in OPEN_STATUSES:
                open_named += 1
                c['open.named'] += 1
                c['lines.open'] += m.lines
        for ini in jt.inits:
            c['init.' + ini.status] += 1
            if ini.status in OPEN_STATUSES:
                c['hidden.initializersOpen'] += 1
                c['lines.open'] += ini.lines
    for m in jf.anon_methods:
        enc = m.enclosing
        if m.const_body and enc is not None and enc.abstract:
            # the constant bodies are the only bodies of an abstract enum method: open when it is
            if enc.status in OPEN_STATUSES:
                c['hidden.enumConstantBodiesOpen'] += 1
                c['lines.open'] += m.lines
        elif enc is not None:
            if enc.status in OPEN_STATUSES:
                c['hidden.anonBodiesInOpenMembers'] += 1
        elif m.owner is not None and not m.owner.scopes and not m.owner.free_matches:
            # in a field initializer or an initializer of a class with no C++: nothing else counts it
            c['hidden.orphanAnonBodiesOpen'] += 1
            c['lines.open'] += m.lines
    bodies = sum(1 for jt in jf.types for m in jt.methods if m.status not in ('enumCtor', 'trivial', 'field', 'omitted', 'replaced'))
    own_h = [f for f in jf.cpp_files if f.endswith('.h') and not f.startswith(CPP_GENERATED) and not f.endswith(('Info.h', '.gen.h'))]
    own_cpp = [f for f in jf.cpp_files if f.endswith('.cpp')]
    if own_h and not own_cpp and bodies:
        c['hidden.headerOnlyShellsWithBodies'] += 1
        if open_named:
            c['hidden.headerOnlyShells'] += 1
            c['hidden.headerOnlyShellBodies'] += open_named
    if not jf.cpp_files:
        if jf.ported_elsewhere:
            c['hidden.javaFilesInOtherCppFile'] += 1
        else:
            c['hidden.javaFilesNoCpp'] += 1
            c['hidden.javaFilesNoCppBodies'] += bodies
            c['hidden.javaFilesNoCppLines'] += jf.lines
    has_cpp = bool(jf.cpp_files) or jf.ported_elsewhere
    if has_cpp:
        c['hidden.undeclaredWithCppFile'] += sum(1 for jt in jf.types for m in jt.methods if m.status == 'undeclared')
    if jf.rel.startswith(CLIENT_PACKETS):
        c['hidden.clientPackets'] += 1
        c['hidden.clientPacketsNoCpp'] += 0 if has_cpp else 1
    if jf.rel.startswith(AI_HANDLERS):
        c['hidden.aiHandlers'] += 1
        c['hidden.aiHandlersNoCpp'] += 0 if has_cpp else 1
        if '/' not in jf.rel[len(AI_HANDLERS):]:
            c['hidden.aiRootHandlers'] += 1
            c['hidden.aiRootHandlersNoCpp'] += 0 if has_cpp else 1


def finish_counter(c):
    """Open bodies = named Java bodies whose status is unported, partial, declaredOnly or undeclared + enum constant bodies of an open
    abstract method + anonymous bodies of classes with no C++ that no member holds + open initializers + AION_UNPORTED/AION_PARTIAL sites
    in C++-only functions nothing else counts (helper sites of kind 'own'). The formula of the first draft (sites + undeclared +
    declaredOnly) is kept as open.siteFormula."""
    c['open.bodies'] = (c['open.named'] + c['hidden.enumConstantBodiesOpen'] + c['hidden.orphanAnonBodiesOpen'] +
                        c['hidden.initializersOpen'] + c['cpp.helperSites.own'])
    c['open.siteFormula'] = c['cpp.unportedSites'] + c['cpp.partialSites'] + c['hidden.undeclared'] + c['hidden.declaredOnly']
    c['open.javaLines'] = c['lines.open']
    c['hidden.notOpen'] = sum(c['status.' + s] for s in ('standIn', 'omitted', 'replaced'))
    return c


def nest(counter):
    """{'a.b': 1} -> {'a': {'b': 1}} (sorted keys)"""
    out = {}
    for key in sorted(counter):
        d = out
        parts = key.split('.')
        for p in parts[:-1]:
            d = d.setdefault(p, {})
        d[parts[-1]] = counter[key]
    return out


def type_record(jf, jt):
    pkg = (jf.package or '').removeprefix('com.aionemu.gameserver.')
    rec = {'type': (pkg + '.' if pkg else '') + '.'.join(jt.path), 'file': jf.rel, 'line': jt.line, 'kind': jt.kind, 'role': jt.role,
           'bodies': len(jt.methods), 'cpp': ['::'.join(s) for s in jt.scopes] or None}
    st = Counter(m.status for m in jt.methods)
    rec['status'] = {k: st[k] for k in STATUS_ORDER if st[k]}
    for key, sel in (('undeclared', lambda m: m.status == 'undeclared'), ('declaredOnly', lambda m: m.status == 'declaredOnly'),
                     ('unported', lambda m: m.status in ('unported', 'partial')), ('arityDiffers', lambda m: m.arity_differs),
                     ('credited', lambda m: m.via or m.status in ('omitted', 'replaced'))):
        lst = [f'{m.name}/{m.arity} L{m.line}' + (f' ({m.undeclared_kind})' if m.undeclared_kind else '') +
               (f' [{m.via or m.status}{": " + m.where if m.where else ""}]' if key == 'credited' else '') +
               (' [named in a C++ comment]' if m.mentioned else '') for m in jt.methods if sel(m)]
        if lst:
            rec[key] = lst
    enc = [f'{m.name}/{m.arity}: {m.status}' for m in jt.abstract]
    if enc:
        rec['abstract'] = enc
    inits = [f"{'static' if i.static else 'instance'} initializer L{i.line}: {i.status}" + (f' ({i.where})' if i.where else '')
             for i in jt.inits]
    if inits:
        rec['initializers'] = inits
    return rec


class Measure:
    """the matched census before aggregation (run() aggregates it; --self-check inspects it)"""

    def __init__(self):
        t0 = time.perf_counter()
        self.manifest = manifest = chunkslib.Manifest.load(chunkslib.DEFAULT_MANIFEST)
        own = chunkslib.Ownership.of_tree(manifest, GAME_SERVER, JAVA_GAME_SERVER)
        self.chunk_order, self.phase_of = [], {}
        for p in manifest.parts:
            if p.lease or p.name in self.phase_of:
                continue
            self.chunk_order.append(p.name)
            self.phase_of[p.name] = p.phase
        self.cpp_owner = {path: parts[0].name for path, parts in own.owners.items() if len(parts) == 1}
        self.java_owner = {path: parts[0].name for path, parts in own.claims.items() if len(parts) == 1}
        self.existing = set(own.cpp_files)
        self.java_set = set(own.java_files)
        t1 = time.perf_counter()
        self.index = index = build_index(own.cpp_files)
        t2 = time.perf_counter()
        ctx = MatchContext(index, self.existing, self.cpp_owner)
        self.jfiles = []
        for rel in own.java_files:
            path = JAVA_GAME_SERVER / rel
            text = path.read_text(encoding='utf-8-sig', errors='replace')
            try:
                cu = javasrc.parse_source(text, str(path))
                jf = analyse_java(rel, cu, text)
            except javasrc.JavaSyntaxError as e:
                jf = JFile(rel, text.count('\n') + 1, error=str(e))
            jf.chunk = self.java_owner.get(rel)
            match_file(jf, index, self.existing, ctx=ctx)
            self.jfiles.append(jf)
        self.helper_sites = finalize(self.jfiles, index)
        t3 = time.perf_counter()
        self.timing = (t0, t1, t2, t3)

    def file_chunk(self, rel):
        """(chunk, package-relative path) of a C++ file; a generated file counts for the chunk that claims its Java file"""
        if rel.startswith('generated/'):
            j = java_for_generated(rel, self.java_set, self.index.files[rel].java if rel in self.index.files else None)
            return (self.java_owner.get(j, 'T2-gen') if j else 'T2-gen'), (package_relative(j) if j else None)
        return self.cpp_owner.get(rel, '(unowned)'), package_relative(rel)

    def helper_list(self):
        """[(chunk, 'file:line name', kind, sites)] of the AION_UNPORTED/AION_PARTIAL sites in functions no Java body maps to"""
        out = []
        for rel, fs in self.index.func_file.items():
            for f in fs:
                if f.helper and (f.unported or f.partial):
                    out.append((self.file_chunk(rel)[0], f'{rel}:{f.line} {"::".join(f.scope[-1:] + (f.name,))}', f.helper,
                                f.unported + f.partial))
        return sorted(out)


def run(args):
    ms_ = Measure()
    t0, t1, t2, t3 = ms_.timing
    manifest, index, jfiles = ms_.manifest, ms_.index, ms_.jfiles
    chunk_order, phase_of, java_owner = ms_.chunk_order, ms_.phase_of, ms_.java_owner

    per_chunk = defaultdict(new_counter)
    per_ms = defaultdict(new_counter)
    ms_chunks = defaultdict(set)
    types = defaultdict(list)
    for jf in jfiles:
        chunk = java_owner.get(jf.rel, '(unclaimed)')
        ms = milestone_of(chunk, phase_of.get(chunk), package_relative(jf.rel))
        aggregate_java(per_chunk[chunk], jf)
        aggregate_java(per_ms[ms], jf)
        ms_chunks[ms].add(chunk)
        if not args.no_types:
            for jt in jf.types:
                if jt.methods or not jt.scopes or jt.inits:
                    types[chunk].append(type_record(jf, jt))
    for rel, st in index.files.items():
        chunk, pkg = ms_.file_chunk(rel)
        key = 'cpp.generatedFiles' if rel.startswith('generated/') else 'cpp.sources' if rel.endswith('.cpp') else 'cpp.headers'
        ms = milestone_of(chunk, phase_of.get(chunk), pkg)
        outside = max(0, st.unported + st.partial - sum(f.unported + f.partial for f in index.func_file.get(rel, ())))
        for c in (per_chunk[chunk], per_ms[ms]):
            c[key] += 1
            if key != 'cpp.generatedFiles':
                c['cpp.files'] += 1
            c['cpp.unportedSites'] += st.unported
            c['cpp.partialSites'] += st.partial
            c['cpp.unportedSitesRaw'] += st.unported_raw
            c['cpp.partialSitesRaw'] += st.partial_raw
            c['cpp.inlineBodies'] += st.inline_bodies
            c['cpp.definedBodies'] += st.defined_bodies
            hs = ms_.helper_sites.get(rel, {})
            for k in HELPER_KINDS:
                c['cpp.helperSites.' + k] += hs.get(k, 0)
            # sites outside any function definition (a namespace-scope initializer) count as C++-only sites
            c['cpp.helperSites.own'] += outside
        ms_chunks[ms].add(chunk)
    helpers = defaultdict(list)
    for chunk, where, kind, n in ms_.helper_list():
        helpers[chunk].append(f'{where} [{kind}] {n}')
    for path, sc in index.scopes.items():
        if sc.kind not in ('class', 'struct', 'union') or not sc.defs:
            continue
        chunk, pkg = ms_.file_chunk(sc.defs[0][0])
        ms = milestone_of(chunk, phase_of.get(chunk), pkg)
        n = sum(1 for name, ents in index.entities.get(path, {}).items() if not name.startswith('~')
                for e in ents if e.member)
        for c in (per_chunk[chunk], per_ms[ms]):
            c['cpp.classes'] += 1
            c['cpp.declaredMethods'] += n
    for c in list(per_chunk.values()) + list(per_ms.values()):
        finish_counter(c)
    t4 = time.perf_counter()

    flux = in_flux(manifest)
    head = (git('rev-parse', '--short', 'HEAD') or '').strip() or None
    selected = [c for c in chunk_order if not args.chunks or c in args.chunks]
    extra = sorted(k for k in per_chunk if k not in phase_of)
    chunks_out = {}
    for c in selected + [k for k in extra if not args.chunks]:
        phase = phase_of.get(c)
        chunks_out[c] = {
            'phase': phase,
            'milestone': (CHUNK_MILESTONE.get(c) if phase == '5' else f'phase {phase}' if phase else None),
            'note': CHUNK_NOTES.get(c),
            'inFlux': (flux or {}).get(c, []),
            **nest(per_chunk[c]),
        }
        if helpers.get(c):
            chunks_out[c]['helperSites'] = helpers[c]
        if not args.no_types:
            chunks_out[c]['types'] = types.get(c, [])

    def section(phase):
        tot = Counter()
        for c in chunk_order:
            if phase_of[c] == phase:
                tot.update(per_chunk[c])
        return nest(finish_counter(tot))

    totals = {'phase4': section('4'), 'phase5': section('5'), 'phase6': section('6')}
    grand = Counter()
    for c in chunk_order:
        grand.update(per_chunk[c])
    totals['all'] = nest(finish_counter(grand))
    milestones = {}
    for key, label in MILESTONES:
        if key in per_ms:
            milestones[key] = {'label': label, 'chunks': sorted(ms_chunks[key]), **nest(per_ms[key])}
    sizes = [(c, per_chunk[c]['java.lines']) for c in chunk_order]
    shards = shard(sizes, 6)
    doc = {
        'format': 'aion-census', 'version': 2, 'generated': datetime.date.today().isoformat(), 'head': head,
        'workingTree': True, 'inFluxAvailable': flux is not None,
        'timing': {'manifest': round(t1 - t0, 1), 'cpp': round(t2 - t1, 1), 'java': round(t3 - t2, 1), 'aggregate': round(t4 - t3, 1)},
        'cppIndex': {'files': len(index.files), 'parsed': sum(1 for s in index.files.values() if s.parsed), 'scopes': len(index.scopes),
                     'functions': len(index.funcs),
                     'unbalanced': sorted(f'{s.rel} ({s.unbalanced})' for s in index.files.values() if s.unbalanced)},
        'javaParseErrors': sorted(f'{jf.rel}: {jf.error}' for jf in jfiles if jf.error),
        'roadmap': ROADMAP,
        'history': history(manifest, args.history) if args.history else {},
        'totals': totals,
        'milestones': milestones,
        'shards': [{'chunks': s, 'javaLines': sum(per_chunk[c]['java.lines'] for c in s)} for s in shards],
        'chunks': chunks_out,
    }
    return doc, chunk_order, phase_of


