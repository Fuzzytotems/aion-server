"""emit: C++ back end of the static data generator (docs/design/static-data.md §2, XmlBinding.h contract).

Writes, for a CppModel:
- enum headers (enum class in ordinal order + EnumTraits name tables);
- data-only class headers (complete structs with public members and the trivial Java accessors);
- behaviour classes: `X.xml.h` (includes and declarations the member block needs, included by the hand-written X.h before the class)
  and `X.xml.inc` (friend binder, aliases, virtual javaClassName, members, trivial accessors, hook declaration: the first line of the
  hand-written class body);
- one `<package>.bind.h` (XmlBinding<T> specializations) and `<package>.bind.cpp` (definitions and @XmlElements factories) per package;
- `dataholders/StaticDataHolders.xml.h` (holder table of StaticData) and `xmlgen-include-root.inc` (include bridge, see there);
- `xmlmodel.json`, `staticdata-classes.json`, `xmlgen-report.md`.
All output is deterministic (sorted, LF line endings).
"""
from __future__ import annotations

import json
from collections import defaultdict

import cppmodel
import jaxb
from cppmodel import cpp_string_literal, fnv1a64
from jaxb import XmlGenError, short_fqn

BANNER = '// GENERATED by tools/xmlgen from {source} - do not edit (regenerate with: python cpp/tools/xmlgen/xmlgen.py generate)'
BIND_CONTEXT = 'aion/gameserver/dataholders/loadingutils/BindContext.h'
ENUM_TRAITS = 'aion/gameserver/dataholders/loadingutils/EnumTraits.h'
XML_NS = '::aion::gameserver::xml'
IR_FORMAT = 'aion-xmlmodel'
IR_VERSION = 1


def java_source(fqn_or_td):
    td = fqn_or_td
    while td.outer is not None:
        td = td.outer
    return td.cu.relpath.replace('com/aionemu/gameserver/', '')


def include_lines(paths):
    std = sorted(p for p in paths if not p.endswith('.h') or p.startswith('<'))
    own = sorted(p for p in paths if p.endswith('.h') and not p.startswith('<'))
    out = []
    out += [f'#include {p}' for p in std]
    if std and own:
        out.append('')
    out += [f'#include "{p}"' for p in own]
    return out


def std_includes(text):
    found = set()
    table = [('std::vector', '<vector>'), ('std::optional', '<optional>'), ('std::unique_ptr', '<memory>'), ('std::string_view', '<string_view>'),
             ('std::string', '<string>'), ('std::unordered_set', '<unordered_set>'), ('int8_t', '<cstdint>'), ('int16_t', '<cstdint>'),
             ('int32_t', '<cstdint>'), ('int64_t', '<cstdint>'), ('uint8_t', '<cstdint>'), ('uint16_t', '<cstdint>'), ('std::array', '<array>'),
             ('std::move', '<utility>')]
    for needle, header in table:
        if needle in text:
            found.add(header)
    return found


class Emitter:
    def __init__(self, cm):
        self.cm = cm
        self.files = {}  # relative path (under generated/) -> text
        self.packages = defaultdict(list)
        for cc in cm.classes.values():
            if not cc.container:
                self.packages[cc.package].append(cc)
        self.forward_needed = {}

    def write(self, path, text):
        if path in self.files:
            raise XmlGenError(f'generated file {path} written twice')
        if not text.endswith('\n'):
            text += '\n'
        self.files[path] = text

    def run(self):
        self.break_include_cycles()
        for e in sorted(self.cm.enums.values(), key=lambda e: e.fqn):
            self.write(e.header, self.enum_header(e))
        for cc in sorted(self.cm.classes.values(), key=lambda c: c.fqn):
            if cc.container:
                self.write(cc.header, self.container_header(cc))
            elif cc.is_data:
                self.write(cc.header, self.data_header(cc))
            else:
                self.write(cc.prelude, self.prelude(cc))
                self.write(cc.inc, self.member_block(cc))
        units = defaultdict(list)
        for cc in self.cm.classes.values():
            if not cc.container:
                units[self.unit_of(cc).fqn].append(cc)
        for package in sorted(self.packages):
            package_units = sorted({self.unit_of(cc).fqn for cc in self.packages[package]})
            ipps = []
            for ufqn in package_units:
                unit = self.cm.classes[ufqn]
                classes = sorted(units[ufqn], key=lambda c: c.fqn)
                base = self.unit_base(unit)
                self.write(base + '.bind.h', self.bind_header(unit, classes))
                self.write(base + '.bind.ipp', self.bind_source(unit, classes, base + '.bind.h'))
                ipps.append(base + '.bind.ipp')
            pkg_file = cppmodel.package_dir(package) + '/' + package.rpartition('.')[2] + '.bind.cpp'
            self.write(pkg_file, '\n'.join([BANNER.format(source=f'package {package}'), '',
                                            f'// Translation unit of the XmlBinding definitions of the bound classes of {package}.', '',
                                            *[f'#include "{p}"' for p in ipps]]))
        holders = self.holders_table()
        if holders:
            self.write('aion/gameserver/dataholders/StaticDataHolders.xml.h', holders)
        self.write('xmlgen-include-root.inc', INCLUDE_ROOT)
        return self.files

    # -- include graph ---------------------------------------------------------------------------------------------------------------------
    def class_include_edges(self, cc):
        """[(target header, strength, target CClass or None)] of the declarations of cc (data header or prelude)"""
        edges = []
        by_header = {}
        for c in self.cm.classes.values():
            by_header.setdefault(c.header, c)
        weak = {}
        for mem in cc.members:
            if mem.prop is None:
                continue
            t = mem.type
            if mem.elem_qualified and ('std::unique_ptr<' in t or t.startswith('const ') or 'const ' in t):
                weak[mem.elem_qualified] = True
        for h in sorted(cc.includes):
            target = by_header.get(h)
            strength = 'complete'
            if target is not None and target.qualified in weak and all(
                    not (mem.elem_qualified == target.qualified and not ('std::unique_ptr<' in mem.type or 'const ' in mem.type))
                    for mem in cc.members):
                strength = 'pointer'
            if target is not None and cc.superclass is target:
                strength = 'complete'
            edges.append((h, strength, target))
        return edges

    def break_include_cycles(self):
        """Pointer-like members (unique_ptr, IDREF pointers) whose headers form an include cycle get forward declarations instead."""
        nodes = {}
        for cc in self.cm.classes.values():
            nodes.setdefault(cc.header, []).append(cc)
        graph = defaultdict(set)
        for cc in self.cm.classes.values():
            for h, _, target in self.class_include_edges(cc):
                if target is not None:
                    graph[cc.header].add(h)
        sccs = tarjan(graph)
        in_cycle = {}
        for i, comp in enumerate(sccs):
            if len(comp) > 1:
                for h in comp:
                    in_cycle[h] = i
        for cc in self.cm.classes.values():
            if cc.header not in in_cycle:
                continue
            for h, strength, target in self.class_include_edges(cc):
                if target is None or in_cycle.get(h) != in_cycle[cc.header]:
                    continue
                if strength != 'pointer':
                    continue
                if target.nested_in_cpp:
                    raise XmlGenError(f'include cycle through the nested class {target.fqn}')
                cc.includes.discard(h)
                cc.forward.add(target.fqn)
        graph = defaultdict(set)
        for cc in self.cm.classes.values():
            for h, _, target in self.class_include_edges(cc):
                if target is not None:
                    graph[cc.header].add(h)
        remaining = [sorted(c) for c in tarjan(graph) if len(c) > 1]
        if remaining:
            raise XmlGenError('include cycles that forward declarations cannot break: ' + '; '.join(', '.join(c) for c in remaining))

    def forward_declarations(self, cc):
        lines = []
        by_ns = defaultdict(list)
        for fqn in sorted(cc.forward):
            t = self.cm.classes[fqn]
            if t.header in cc.includes or t.header == cc.header:
                continue
            if t.nested_in_cpp:
                cc.includes.add(t.header)
                continue
            key = 'struct' if t.is_data else 'class'
            by_ns[t.namespace].append(f'{key} {t.cpp_name};')
        for ns in sorted(by_ns):
            lines.append(f'namespace {ns} {{')
            lines += sorted(set(by_ns[ns]))
            lines.append(f'}} // namespace {ns}')
        return lines

    # -- enums ---------------------------------------------------------------------------------------------------------------------------
    def enum_header(self, e):
        source = java_source(e.model.td) if e.model.td is not None else f'xmlgen.toml [external_enums] {e.fqn}'
        n = len(e.constants)
        lines = ['#pragma once', BANNER.format(source=source), '', *include_lines({'<array>', '<cstdint>', '<string_view>', ENUM_TRAITS}), '',
                 f'namespace {e.namespace} {{', '']
        doc = f'/** Java enum {e.fqn}: constants in ordinal order (EnumTraits: names and XML lexical forms).'
        if e.model.has_methods or e.model.has_constructor_args or e.model.has_fields:
            doc += ' Constructor data and methods are hand-written free functions in a companion header.'
        lines.append(doc + ' */')
        lines.append(f'enum class {e.cpp_name} : {e.underlying} {{')
        for java, cpp, _ in e.constants:
            lines.append(f'\t{cpp},' + (f' // Java {java}' if cpp != java else ''))
        lines += ['};', '', f'}} // namespace {e.namespace}', '', 'namespace aion::gameserver::xml {', '', 'template <>',
                  f'struct EnumTraits<{e.qualified}> {{', f'\tstatic constexpr std::string_view javaName = "{e.java_name}";',
                  f'\tstatic constexpr std::array<std::string_view, {n}> names{{']
        for java, _, _ in e.constants:
            lines.append(f'\t  "{java}",')
        lines.append('\t};')
        lines.append(f'\tstatic constexpr std::array<EnumEntry<{e.qualified}>, {n}> xmlSorted{{{{')
        for java, cpp, xml in sorted(e.constants, key=lambda c: c[2].encode('utf-8')):
            lines.append(f'\t  {{{cpp_string_literal(xml)}, {e.qualified}::{cpp}}},')
        if n <= 256:
            check = f'static_assert(verifyEnumTraits<{e.qualified}>());'
        else:  # verifyEnumTraits is quadratic and exceeds the constexpr step limit; the generator guarantees ordinal coverage
            check = f'static_assert(isStrictlySortedByName(EnumTraits<{e.qualified}>::xmlSorted));'
        lines += ['\t}};', '};', check, '', '} // namespace aion::gameserver::xml']
        return '\n'.join(lines)

    # -- class declarations ----------------------------------------------------------------------------------------------------------------
    def member_lines(self, cc, section_access=True):
        """[(access, line)] of members, aliases, virtuals, accessors and the hook declaration"""
        out = []
        for alias, qualified, access in cc.aliases:
            out.append((access, f'using {alias} = {qualified};'))
        if cc.polymorphic_root:
            out.append(('public', f'virtual ~{cc.cpp_name}() = default;'))
            if cc.model.abstract:
                out.append(('public', 'virtual std::string_view javaClassName() const = 0; // Java getClass().getSimpleName()'))
            else:
                out.append(('public', f'virtual std::string_view javaClassName() const {{ return "{cc.java_name}"; }}'))
        elif cc.polymorphic and not cc.model.abstract:
            out.append(('public', f'std::string_view javaClassName() const override {{ return "{cc.java_name}"; }}'))
        for mem in cc.members:
            if mem.bind == 'methodSetter':
                continue
            init = ''
            if mem.init:
                init = f'{{{mem.init}}}' if mem.type.startswith('mutable ') else f' = {mem.init}'
            out.append((mem.access, f'{mem.type} {mem.name}{init}; // {mem.comment}'))
        for st in cc.statics:
            out.append(('public', st.code))
        for acc in cc.accessors:
            out.append((acc.access, acc.code))
        for mem in cc.members:
            if mem.bind == 'methodSetter':
                setter = next(m for m in cc.model.td.methods if m.name == mem.prop.setter and len(m.params) == 1)
                ptype = 'std::string_view' if mem.scalar_cpp == 'std::string' else mem.scalar_cpp
                access = {'package': 'public'}.get(jaxb._access(setter.modifiers), jaxb._access(setter.modifiers))
                out.append((access, f'void {setter.name}({ptype} {cppmodel.cpp_ident(setter.params[0].name)}); // hand-written, {mem.comment}'))
        if not cc.is_data and cc.model.hook is not None:
            hook_access = {'private': 'private', 'public': 'public'}.get(jaxb._access(cc.model.hook.modifiers), 'protected')
            out.append((hook_access, f'void afterUnmarshal({XML_NS}::LoadContext& ctx, const {XML_NS}::XmlParent& parent); // hand-written'))
        return out

    def data_header(self, cc):
        c = cc.model
        body = self.member_lines(cc)
        text_for_std = '\n'.join(line for _, line in body) + (' std::string_view' if cc.polymorphic else '')
        includes = set(cc.includes) | std_includes(text_for_std)
        forward = self.forward_declarations(cc)
        includes = set(cc.includes) | std_includes(text_for_std)
        lines = ['#pragma once', BANNER.format(source=java_source(c.td)), '', *include_lines(includes), '']
        if forward:
            lines += forward + ['']
        lines += [f'namespace {cc.namespace} {{', '']
        doc = f'/** Java {c.fqn} (data-only: generated completely). */'
        base = f' : public {cc.superclass.qualified}' if cc.superclass else ''
        lines += [doc, f'struct {cc.cpp_name}{base} {{']
        lines += [f'\t{line}' for _, line in body]
        lines.append('};')
        defs = [st.definition for st in cc.statics if st.definition]
        if defs:
            lines += [''] + defs
        lines += ['', f'}} // namespace {cc.namespace}']
        return '\n'.join(lines)

    def container_header(self, cc):
        lines = ['#pragma once', BANNER.format(source=java_source(cc.model.td)), '', *include_lines(set(cc.includes)), '',
                 f'namespace {cc.namespace} {{', '', f'/** Java {cc.fqn}: only encloses bound nested classes (generated at namespace scope). */',
                 f'struct {cc.cpp_name} {{']
        for alias, qualified, _ in cc.aliases:
            lines.append(f'\tusing {alias} = {qualified};')
        for st in cc.statics:
            lines.append(f'\t{st.code}')
        lines += ['};', '', f'}} // namespace {cc.namespace}']
        return '\n'.join(lines)

    def prelude(self, cc):
        c = cc.model
        body = self.member_lines(cc)
        text = '\n'.join(line for _, line in body) + (' std::string_view' if cc.polymorphic else '')
        forward = self.forward_declarations(cc)
        includes = set(cc.includes) | std_includes(text) | {cppmodel.FWD_HEADER}
        for n in self.cm.classes.values():
            if n.outer is cc and n.nested_in_cpp:
                includes.add(n.prelude)
        lines = ['#pragma once', BANNER.format(source=java_source(c.td)), '',
                 f'// Declarations used by the member block {cc.inc.rpartition("/")[2]} of {c.fqn}.',
                 f'// The hand-written {cc.header.rpartition("/")[2]} includes this header before the class definition.', '',
                 *include_lines(includes)]
        if forward:
            lines += [''] + forward
        return '\n'.join(lines)

    def member_block(self, cc):
        c = cc.model
        lines = [BANNER.format(source=java_source(c.td)),
                 f'// Member block of {c.fqn}: `#include "{cc.inc}"` is the first line of the hand-written class body and must be',
                 '// followed by an explicit access specifier.',
                 f'\tfriend struct {XML_NS}::XmlBinding<{cc.qualified}>;']
        nested = sorted(n.java_name for n in self.cm.classes.values() if n.outer is cc and n.nested_in_cpp)
        body = []
        for name in nested:
            n = next(x for x in self.cm.classes.values() if x.outer is cc and x.java_name == name)
            # public in C++ whatever the Java access: XmlBinding<Outer::Inner> is declared at namespace scope
            body.append(('public', f'class {name}; // hand-written nested class, defined after {cc.java_name}'))
        body += self.member_lines(cc)
        current = None
        for access, line in body:
            if access != current:
                lines += ['', f'{access}:']
                current = access
            lines.append(f'\t{line}')
        return '\n'.join(lines)

    # -- binders -------------------------------------------------------------------------------------------------------------------------
    def unit_of(self, cc):
        """the top-level Java class whose source file declares cc (binder files are per source file)"""
        while cc.outer is not None:
            cc = cc.outer
        return cc

    def unit_base(self, unit):
        return f'{cppmodel.package_dir(unit.package)}/{unit.java_name}'

    def bind_header(self, unit, classes):
        includes = {BIND_CONTEXT, '<memory>', '<string_view>'}
        for cc in classes:
            includes.add(cc.header)
        lines = ['#pragma once', BANNER.format(source=java_source(unit.model.td)), '',
                 f'// XmlBinding specializations of {unit.fqn}{" and its nested classes" if len(classes) > 1 or classes[0] is not unit else ""}'
                 ' (contract: dataholders/loadingutils/XmlBinding.h).',
                 '// Included by binder translation units only, never by game code.', '', *include_lines(includes), '',
                 'namespace aion::gameserver::xml {']
        for cc in classes:
            q = cc.qualified
            lines += ['', 'template <>', f'struct XmlBinding<{q}> {{', f'\tstatic constexpr std::string_view CLASS_NAME = "{cc.java_name}";']
            if cc.has_attribute:
                lines.append(f'\tstatic bool attribute({q}& o, BindContext& c, std::string_view name, std::string_view value);')
            if cc.has_element:
                lines.append(f'\tstatic bool element({q}& o, BindContext& c, pugi::xml_node e, std::string_view name);')
            if cc.has_reserve:
                lines.append(f'\tstatic void reserve({q}& o, const ChildCounts& counts);')
            if cc.has_finish:
                lines.append(f'\tstatic void finish({q}& o, BindContext& c, const XmlParent& parent);')
            if cc.create:
                lines.append(f'\tstatic std::unique_ptr<{q}> create();')
            if cc.model.hook is not None:
                lines.append(f'\t/** calls the hand-written {cc.java_name}::afterUnmarshal (also for subclasses without their own hook) */')
                lines.append(f'\tstatic void afterUnmarshal({q}& o, LoadContext& ctx, const XmlParent& parent);')
            lines.append('};')
        lines += ['', '} // namespace aion::gameserver::xml']
        return '\n'.join(lines)

    def bind_source(self, unit, classes, own_header):
        includes = {own_header, '<memory>', '<string_view>'}
        deps = set()
        for cc in classes:
            if cc.superclass is not None:
                deps.add(self.unit_of(cc.superclass).fqn)
            if cc.hook_owner is not None:
                deps.add(self.unit_of(cc.hook_owner).fqn)
            for mem in cc.members:
                p = mem.prop
                if p is None:
                    continue
                if mem.bind in ('bindSingle', 'bindList', 'wrapper') and mem.elem_qualified:
                    deps.add(self.unit_of(self.class_by_qualified(mem.elem_qualified)).fqn)
                if mem.bind == 'classAdapter':
                    vt = self.class_by_qualified(mem.elem_qualified)
                    deps.add(self.unit_of(vt).fqn)
                    includes.add(vt.header)
                if mem.bind.endswith('LenientEnum'):  # enumFromXml/trimXml/std::string in the generated statements
                    includes |= {'<optional>', '<string>', ENUM_TRAITS, 'aion/gameserver/dataholders/loadingutils/XmlValues.h'}
                if p.idref:  # LoadContext::addIdRef uses typeid(T): the target must be complete
                    includes.add(self.class_by_qualified(mem.elem_qualified).header)
                if mem.bind == 'choice':
                    for f in cc.factories:
                        if f.name == mem.factory:
                            for _, _, target in f.entries:
                                deps.add(self.unit_of(target).fqn)
                                includes.add(target.header)
            for f in cc.factories:
                includes.add(self.class_by_qualified(f.base_qualified).header)
        for dep in deps:
            if dep != unit.fqn:
                includes.add(self.unit_base(self.cm.classes[dep]) + '.bind.h')
        lines = [BANNER.format(source=java_source(unit.model.td)), '',
                 f'// XmlBinding definitions of {unit.fqn}; compiled through the package translation unit '
                 f'{unit.package.rpartition(".")[2]}.bind.cpp.', '', *include_lines(includes), '', 'namespace aion::gameserver::xml {']
        factories = [f for cc in classes for f in cc.factories]
        if factories:
            lines += ['', 'namespace {']
            for f in factories:
                lines += ['', f'constexpr ChoiceEntry<{f.base_qualified}> {f.name}_CHOICES[] = {{']
                for xml, derived, _ in f.entries:
                    lines.append(f'  choice<{f.base_qualified}, {derived}>({cpp_string_literal(xml)}),')
                lines += ['};', f'static_assert(isStrictlySortedByName({f.name}_CHOICES));',
                          f'constexpr ElementFactory<{f.base_qualified}> {f.name}_FACTORY{{{f.name}_CHOICES}};']
            lines += ['', '} // namespace']
        for cc in classes:
            lines += self.binding_definitions(cc)
        lines += ['', '} // namespace aion::gameserver::xml']
        return '\n'.join(lines)

    def class_by_qualified(self, qualified):
        for cc in self.cm.classes.values():
            if cc.qualified == qualified:
                return cc
        raise XmlGenError(f'unknown class {qualified}')

    def binding_definitions(self, cc):
        q = cc.qualified
        out = []
        base = cc.superclass
        attrs = [m for m in cc.members if m.prop is not None and m.prop.node == 'attribute']
        elems = [m for m in cc.members if m.prop is not None and m.prop.node in ('element', 'choice')]
        if cc.has_attribute:
            out += ['', f'bool XmlBinding<{q}>::attribute({q}& o, BindContext& c, std::string_view name, std::string_view value) {{']
            entries = [(m.prop.xml_name, self.attribute_statements(m)) for m in attrs]
            entries += [(n, [f'static_cast<void>(value); // not bound by Java, ignored like JAXB (xmlgen.toml [ignore_attributes]: {reason})'])
                        for n, reason in cc.model.ignored_attributes]
            out += self.name_dispatch(entries, 'name')
            if base is not None and base.has_attribute:
                out.append(f'\treturn XmlBinding<{base.qualified}>::attribute(o, c, name, value);')
            else:
                out.append('\treturn false;')
            out.append('}')
            if not entries and not (base is not None and base.has_attribute):
                raise XmlGenError('internal: attribute function without attributes')
        if cc.has_element:
            out += ['', f'bool XmlBinding<{q}>::element({q}& o, BindContext& c, pugi::xml_node e, std::string_view name) {{']
            named = [(m.prop.xml_name if not m.prop.wrapper else m.prop.wrapper, self.element_statements(m)) for m in elems if m.bind != 'choice']
            out += self.name_dispatch(named, 'name')
            for m in elems:
                if m.bind == 'choice':
                    out += [f'\tif (c.bindChoice(o.{m.name}, {m.factory}_FACTORY, e, name))', '\t\treturn true;']
            if base is not None and base.has_element:
                out.append(f'\treturn XmlBinding<{base.qualified}>::element(o, c, e, name);')
            else:
                out.append('\treturn false;')
            out.append('}')
        if cc.has_reserve:
            out += ['', f'void XmlBinding<{q}>::reserve({q}& o, const ChildCounts& counts) {{']
            for m in cc.members:
                if m.reserve:
                    out.append(f'\to.{m.name}.reserve(counts[{cpp_string_literal(m.prop.xml_name)}]);')
            if base is not None and base.has_reserve:
                out.append(f'\tXmlBinding<{base.qualified}>::reserve(o, counts);')
            out.append('}')
        if cc.has_finish:
            hook = cc.hook_owner
            uses_o = hook is not None
            out += ['', f'void XmlBinding<{q}>::finish({q}&{" o" if uses_o else ""}, BindContext& c, const XmlParent&{" parent" if uses_o else ""}) {{']
            if cc.required_attributes:
                out.append('\tc.checkRequiredAttributes({' + ', '.join(cpp_string_literal(n) for n in cc.required_attributes) + '});')
            if cc.required_elements:
                out.append('\tc.checkRequiredElements({' + ', '.join(cpp_string_literal(n) for n in cc.required_elements) + '});')
            if hook is not None:
                out += ['\tif (c.hooksEnabled())', f'\t\tXmlBinding<{hook.qualified}>::afterUnmarshal(o, c.load(), parent);']
            out.append('}')
        if cc.create:
            out += ['', f'std::unique_ptr<{q}> XmlBinding<{q}>::create() {{', f'\treturn std::unique_ptr<{q}>(new {q}());', '}']
        if cc.model.hook is not None:
            out += ['', f'void XmlBinding<{q}>::afterUnmarshal({q}& o, LoadContext& ctx, const XmlParent& parent) {{',
                    '\to.afterUnmarshal(ctx, parent);', '}']
        return out

    def name_dispatch(self, entries, var):
        """switch over nameHash with a full compare per case; an if chain when two names of the dispatch collide"""
        if not entries:
            return []
        hashes = defaultdict(list)
        for name, stmts in entries:
            hashes[fnv1a64(name)].append((name, stmts))
        out = []
        if any(len(v) > 1 for v in hashes.values()) or len(entries) < 3:
            for name, stmts in entries:
                out.append(f'\tif ({var} == {cpp_string_literal(name)}) {{')
                out += [f'\t\t{s}' for s in stmts]
                out += ['\t\treturn true;', '\t}']
            return out
        out.append(f'\tswitch (nameHash({var})) {{')
        for name, stmts in entries:
            out.append(f'\t\tcase {cpp_string_literal(name)}_xh:')
            out.append(f'\t\t\tif ({var} == {cpp_string_literal(name)}) {{')
            out += [f'\t\t\t\t{s}' for s in stmts]
            out += ['\t\t\t\treturn true;', '\t\t\t}', '\t\t\tbreak;']
        out.append('\t}')
        return out

    def attribute_statements(self, m):
        p = m.prop
        b = m.bind
        if b == 'assign':
            return [f'c.assign(o.{m.name}, value);']
        if b == 'assignXmlId':
            return [f'c.assign(o.{m.name}, value);', 'c.registerXmlId(value, o);']
        if b == 'assignList':
            return [f'c.assignList(o.{m.name}, value);']
        if b == 'assignLenientEnum':
            return self.lenient_enum_statements(m, 'value', f'{p.owner.td.name}@{p.xml_name}')
        if b == 'adapterAttribute':
            return [f'o.{m.name} = {m.adapter["parse"]}(c, value);']
        if b == 'idRef':
            return [f'c.idRef(o.{m.name}, value);']
        if b == 'idRefList':
            return [f'c.idRefList(o.{m.name}, value);']
        if b == 'fieldAttribute':
            return [f'o.{m.name}.set(c.value<{m.scalar_cpp}>(value));']
        if b == 'methodSetter':
            arg = 'value' if m.scalar_cpp == 'std::string' else f'c.value<{m.scalar_cpp}>(value)'
            stmts = [f'o.{p.setter}({arg});']
            if p.xml_id:
                stmts.append('c.registerXmlId(value, o);')
            return stmts
        raise XmlGenError(f'{p.location}: internal: attribute binding {b}')

    def lenient_enum_statements(self, m, var, key):
        """[lenient_enums]: JAXB's enum leaf returns null for an unknown lexical value (no event); warn once and store nullopt"""
        e = m.scalar_cpp
        reason = self.cm.policy.lenient_enums[m.prop.key]['reason']
        message = f"unknown {m.prop.value_type.fqn.rsplit('.', 1)[-1]} constant '"
        tail = f"' is null like JAXB (xmlgen.toml [lenient_enums]: {reason})"
        return [f'if (std::optional<{e}> constant = enumFromXml<{e}>(trimXml({var}))) {{',
                f'\to.{m.name} = *constant;',
                '} else {',
                f'\to.{m.name}.reset();',
                f'\tc.warnOnce({cpp_string_literal(key)}, {cpp_string_literal(message)} + std::string({var}) + {cpp_string_literal(tail)});',
                '}']

    def element_statements(self, m):
        p = m.prop
        b = m.bind
        if b == 'bindText':
            return [f'c.bindText(o.{m.name}, e);']
        if b == 'bindTextXmlId':
            return [f'c.bindText(o.{m.name}, e);', f'c.registerXmlId(o.{m.name}, o);']
        if b == 'bindList':
            return [f'c.bindList(o.{m.name}, e);']
        if b == 'bindTextList':
            return [f'c.bindTextList(o.{m.name}, e);']
        if b == 'bindTextLenientEnum':
            return ['std::string text = c.elementText(e);'] + self.lenient_enum_statements(m, 'text', f'{p.owner.td.name}<{p.xml_name}>')
        if b == 'bindSingle':
            return [f'c.bindSingle(o.{m.name}, e);']
        if b == 'wrapper':
            return [f'c.bindWrapper(o.{m.name}, e, {cpp_string_literal(p.xml_name)});']
        if b in ('idRefText',):
            return [f'c.idRefText(o.{m.name}, e);']
        if b == 'idRef':
            return [f'c.idRefText(o.{m.name}, e);']
        if b == 'adapterText':
            return [f'o.{m.name} = c.adaptText([](std::string_view text) {{ return {m.adapter["parse"]}(text); }}, e);']
        if b == 'fieldText':
            return [f'o.{m.name}.set(c.value<{m.scalar_cpp}>(c.elementText(e)));']
        if b == 'classAdapter':
            stmts = [f'std::unique_ptr<{m.elem_qualified}> value = constructBound<{m.elem_qualified}>();',
                     'c.bindObject(*value, e, c.currentObject());']
            stmts += m.adapter['unmarshal'].replace('{member}', m.name).split('\n')
            return stmts
        raise XmlGenError(f'{p.location}: internal: element binding {b}')

    # -- StaticData holders --------------------------------------------------------------------------------------------------------------
    def holders_table(self):
        roots = [cc for cc in self.cm.classes.values() if cc.model.xml_root_element == 'static_data']
        if not roots:
            return None
        if len(roots) > 1:
            raise XmlGenError('several classes with @XmlRootElement(name = "static_data")')
        sd = roots[0]
        lines = ['#pragma once', BANNER.format(source=java_source(sd.model.td)), '',
                 '// The holder fields of StaticData in declaration order, as an X-macro: X(rootTag, HolderClass, javaFieldName).',
                 '// DataManager builds its HolderRegistry from it: HolderRegistration::of<HolderClass>(rootTag, dependencies).',
                 '// Holder headers are not included here (they are hand-written or generated class headers).', '',
                 '#define AION_STATIC_DATA_HOLDERS(X) \\']
        rows = []
        for mem in sd.members:
            p = mem.prop
            if p is None or p.node != 'element' or p.collection or p.value_type.kind != 'class':
                raise XmlGenError(f'{p.location if p else sd.model.location}: unexpected StaticData member')
            rows.append(f'\tX({cpp_string_literal(p.xml_name)}, {mem.elem_qualified}, {mem.name})')
        lines += [r + ' \\' for r in rows[:-1]] + [rows[-1]]
        return '\n'.join(lines)


