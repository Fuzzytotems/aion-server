"""sysmsg: generates the static SM_SYSTEM_MESSAGE factories (STR_*) from SM_SYSTEM_MESSAGE.java.

Input:  game-server/src/com/aionemu/gameserver/network/aion/serverpackets/SM_SYSTEM_MESSAGE.java (4,120 `public static` factories, most of
        them `return new SM_SYSTEM_MESSAGE(<msg id>, <parameters>);`)
Output (under cpp/game-server/src/aion/gameserver/, committed; docs/design/handlers-and-porting-plan.md §2.3):
    network/aion/serverpackets/SM_SYSTEM_MESSAGE.gen.h         member block with the factory declarations (and javadoc), #included inside
                                                               the body of the hand-written class; its header comment holds the report
    network/aion/serverpackets/SM_SYSTEM_MESSAGE.gen0..7.cpp   the definitions, split into 8 translation units in source order

Contract with the hand-written class (network/aion/serverpackets/SM_SYSTEM_MESSAGE.h, P4-06):
    SM_SYSTEM_MESSAGE(int32_t msgId, std::vector<std::string> params)       Java: SM_SYSTEM_MESSAGE(int msgId, Object... params)
    static std::string toJavaString(int32_t / int64_t / int8_t / float)     Java: String.valueOf for int, long, byte, float
    The block is included in a public section, after <cstdint>, <string>, <string_view> and <vector>.

Translation of the Java parameters (each argument is formatted when the packet is constructed, like writeImpl's param.toString()):
    String -> std::string_view, copied; int -> int32_t, long -> int64_t, byte -> int8_t, float -> float, formatted with toJavaString.
    Arguments may be a parameter, an int/long/String literal, or a String concatenation ('+' with at least one String operand on the left side
    of each '+', Java's left-to-right typing) of those. Any other parameter type (the 3 factories taking a Player) makes the factory a
    hand-ported one: it is listed in the report and not generated. A body that is neither generated nor hand-ported fails the generator.
    Unused parameters are emitted unnamed. Java identifiers that are C++ keywords or macros get a trailing underscore (dialogaction.py).
    Java returns AionServerPacket from one factory; C++ always returns SM_SYSTEM_MESSAGE (listed in the report).

Usage: python sysmsg.py [--java-dir GAME_SERVER_DIR] [--out-dir CPP_GAME_SERVER_SRC] [--check] [--report]
"""
from __future__ import annotations

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import javasrc  # noqa: E402
from dialogaction import cpp_identifier  # noqa: E402

GEN_DIR = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(GEN_DIR, '..', '..', '..'))
DEFAULT_JAVA_DIR = os.path.join(REPO, 'game-server')
DEFAULT_OUT_DIR = os.path.join(REPO, 'cpp', 'game-server', 'src', 'aion', 'gameserver')

SYSMSG_JAVA = 'src/com/aionemu/gameserver/network/aion/serverpackets/SM_SYSTEM_MESSAGE.java'
OUT_PREFIX = 'network/aion/serverpackets/SM_SYSTEM_MESSAGE'
HEADER_OUT = OUT_PREFIX + '.gen.h'
SOURCE_COUNT = 8
CLASS = 'SM_SYSTEM_MESSAGE'

# Java parameter type -> (C++ parameter type, formatting kind)
PARAM_TYPES = {
    'String': ('std::string_view', 'string'),
    'int': ('int32_t', 'number'),
    'long': ('int64_t', 'number'),
    'byte': ('int8_t', 'number'),
    'float': ('float', 'number'),
}
# Parameter types that make a factory hand-ported (their bodies read game objects)
HAND_PORTED_TYPES = frozenset(['Player'])
FACTORY_RETURN_TYPES = frozenset([CLASS, 'AionServerPacket'])
HEADER_NOTE = '// Generated by cpp/tools/gen/sysmsg.py - do not edit. Regenerate with: python cpp/tools/gen/sysmsg.py'


class GenError(Exception):
    """Unexpected input: the message starts with path:line:col: when a source position is known."""


def _fail(cu, index, message):
    line, col = cu.tokens.loc(index)
    return GenError(f'{cu.path}:{line}:{col}: {message}')


def cpp_string_literal(cu, index, text):
    out = ['"']
    for c in text:
        o = ord(c)
        if c == '"' or c == '\\':
            out.append('\\' + c)
        elif 0x20 <= o < 0x7F:
            out.append(c)
        else:
            raise _fail(cu, index, f'unsupported character U+{o:04X} in string literal {text!r}')
    out.append('"')
    return ''.join(out)


def javadoc_lines(cu, index, doc):
    if doc is None:
        return []
    body = doc.strip()
    if not (body.startswith('/**') and body.endswith('*/')):
        raise _fail(cu, index, 'unexpected javadoc format')
    lines = []
    for raw in body[3:-2].replace('\r\n', '\n').split('\n'):
        line = raw.strip()
        if line.startswith('*'):
            line = line[1:].strip()
        if any(ord(ch) < 0x20 and ch != '\t' for ch in line):
            raise _fail(cu, index, f'control character in javadoc {line!r}')
        lines.append(line.replace('\t', ' ').rstrip())
    while lines and not lines[0]:
        lines.pop(0)
    while lines and not lines[-1]:
        lines.pop()
    return lines


class Factory:
    def __init__(self, method, doc):
        self.method = method
        self.name = method.name
        self.cpp_name = cpp_identifier(method.name)
        self.params = [(str(p.type), p.name) for p in method.params]
        self.doc = doc
        self.kind = None  # 'plain' | 'generated' | 'hand'
        self.msg_id = None
        self.args = []  # C++ argument expressions
        self.notes = []  # why a generated factory is not plain, or why it is hand-ported
        self.used = set()
        self.java_expr = ''

    def java_signature(self):
        return f'{self.name}({", ".join(f"{t} {n}" for t, n in self.params)})'

    def cpp_params(self, with_names):
        parts = []
        for t, n in self.params:
            cpp_type = PARAM_TYPES[t][0]
            if with_names and n in self.used:
                parts.append(f'{cpp_type} {cpp_identifier(n)}')
            elif with_names:
                parts.append(f'{cpp_type} /*{cpp_identifier(n)}*/')
            else:
                parts.append(f'{cpp_type} {cpp_identifier(n)}')
        return ', '.join(parts)


def split_args(cu, start, end):
    """Top-level comma separated token ranges between start and end (exclusive)."""
    t = cu.tokens
    ranges = []
    s = start
    i = start
    while i < end:
        if t.kind[i] == javasrc.OP and t.text[i] in ('(', '[', '{') and t.match[i] >= 0:
            i = t.match[i] + 1
            continue
        if t.text[i] == ',':
            ranges.append((s, i))
            s = i + 1
        i += 1
    ranges.append((s, end))
    for a, b in ranges:
        if a >= b:
            raise _fail(cu, a, 'empty argument')
    return ranges


def translate_arg(cu, factory, start, end):
    """C++ expression producing the std::string that Java's param.toString() gives for the argument tokens [start, end)."""
    t = cu.tokens
    param_types = {n: ty for ty, n in factory.params}
    operands = []  # (java type, kind, C++ first-position expression, C++ later-position expression)
    i = start
    expect_operand = True
    while i < end:
        text, kind = t.text[i], t.kind[i]
        if expect_operand:
            negative = False
            if text == '-' and i + 1 < end and t.kind[i + 1] == javasrc.INT:
                negative = True
                i += 1
                text, kind = t.text[i], t.kind[i]
            if kind == javasrc.IDENT and not negative:
                if text not in param_types:
                    raise _fail(cu, i, f'{factory.name}: argument {text} is not a parameter')
                java_type = param_types[text]
                if java_type not in PARAM_TYPES:
                    raise _fail(cu, i, f'{factory.name}: parameter type {java_type} is not supported')
                factory.used.add(text)
                name = cpp_identifier(text)
                if PARAM_TYPES[java_type][1] == 'string':
                    operands.append(('String', f'std::string({name})', f'std::string({name})'))
                else:
                    operands.append((java_type, f'toJavaString({name})', f'toJavaString({name})'))
            elif kind == javasrc.STRING and not negative:
                literal = cpp_string_literal(cu, i, javasrc.literal_value(kind, text))
                operands.append(('String', f'std::string({literal})', literal))
            elif kind == javasrc.INT:
                value = javasrc.literal_value(kind, text)
                is_long = text[-1] in 'lL'
                value = -value if negative else value
                if is_long:
                    if not -2**63 <= value < 2**63:
                        raise _fail(cu, i, 'long literal out of range')
                    expr = f'toJavaString(int64_t{{{value}}})' if value != -2**63 else 'toJavaString(INT64_MIN)'
                    operands.append(('long', expr, expr))
                else:
                    if not -2**31 <= value < 2**31:
                        raise _fail(cu, i, 'int literal out of range')
                    expr = f'toJavaString(int32_t{{{value}}})' if value != -2**31 else 'toJavaString(INT32_MIN)'
                    operands.append(('int', expr, expr))
            else:
                raise _fail(cu, i, f'{factory.name}: unsupported argument expression {t.source_text(start, end)!r}')
            expect_operand = False
        else:
            if text != '+':
                raise _fail(cu, i, f'{factory.name}: unsupported operator {text!r} in {t.source_text(start, end)!r}')
            expect_operand = True
        i += 1
    if expect_operand:
        raise _fail(cu, end - 1, f'{factory.name}: incomplete argument expression {t.source_text(start, end)!r}')
    if len(operands) == 1:
        java_type, first, _ = operands[0]
        if java_type == 'String' and first.startswith('std::string("'):
            return first, True
        return first, False
    # Java: '+' is left associative; it is a String concatenation only if one of its two operands is a String
    acc_type, expr, _ = operands[0]
    for java_type, _, later in operands[1:]:
        if acc_type != 'String' and java_type != 'String':
            raise _fail(cu, start, f'{factory.name}: numeric addition in {t.source_text(start, end)!r} is not supported')
        expr = f'{expr} + {later}'
        acc_type = 'String'
    return expr, True


def classify(cu, factory):
    m = factory.method
    t = cu.tokens
    for java_type, name in factory.params:
        if java_type in HAND_PORTED_TYPES:
            factory.kind = 'hand'
            factory.notes.append(f'parameter {java_type} {name}')
    for p in m.params:
        if p.varargs or p.annotations or p.modifiers:
            raise _fail(cu, p.index, f'{factory.name}: unsupported parameter form')
    if factory.kind == 'hand':
        factory.java_expr = ' '.join(t.source_text(m.body.start + 1, m.body.end - 1).split())
        return
    for java_type, name in factory.params:
        if java_type not in PARAM_TYPES:
            raise _fail(cu, m.index, f'{factory.name}: unsupported parameter type {java_type} (add it to PARAM_TYPES or HAND_PORTED_TYPES)')
    texts = m.body.texts()
    # { return new SM_SYSTEM_MESSAGE ( <args> ) ; }
    s = m.body.start
    if not (len(texts) >= 9 and texts[:5] == ['{', 'return', 'new', CLASS, '('] and texts[-3:] == [')', ';', '}']
            and t.match[s + 4] == m.body.end - 3):
        raise _fail(cu, m.index, f'{factory.name}: unsupported body {m.body.text!r}')
    factory.java_expr = ' '.join(t.source_text(s + 1, m.body.end - 2).split())
    args = split_args(cu, s + 5, m.body.end - 3)
    a, b = args[0]
    if b - a != 1 or t.kind[a] != javasrc.INT or t.text[a][-1] in 'lL':
        raise _fail(cu, a, f'{factory.name}: the message id must be an int literal')
    factory.msg_id = javasrc.literal_value(javasrc.INT, t.text[a])
    if not 0 <= factory.msg_id < 2**31:
        raise _fail(cu, a, f'{factory.name}: message id out of range')
    non_plain = []
    passed_names = []
    for a, b in args[1:]:
        expr, computed = translate_arg(cu, factory, a, b)
        factory.args.append(expr)
        source = ' '.join(t.source_text(a, b).split())
        if b - a == 1 and t.kind[a] == javasrc.IDENT:
            passed_names.append(t.text[a])
        elif computed and b - a > 1:
            non_plain.append(f'computed argument {source}')
        else:
            non_plain.append(f'literal argument {source}')
    param_names = [n for _, n in factory.params]
    if len(set(passed_names)) != len(passed_names):
        non_plain.append('a parameter is passed more than once')
    elif passed_names != [n for n in param_names if n in passed_names]:
        non_plain.append('parameters passed in a different order')
    unused = [n for n in param_names if n not in factory.used]
    if unused:
        non_plain.append('unused parameter ' + ', '.join(unused))
    if str(m.return_type) != CLASS:
        non_plain.append(f'Java return type {m.return_type} (C++: {CLASS})')
    if factory.cpp_name != factory.name:
        non_plain.append(f'C++ name {factory.cpp_name}')
    factory.notes = non_plain
    factory.kind = 'generated' if non_plain else 'plain'


def parse(java_dir):
    path = os.path.join(java_dir, SYSMSG_JAVA)
    if not os.path.isfile(path):
        raise GenError(f'missing Java source: {path}')
    cu = javasrc.parse_file(path)
    tds = [td for td in cu.types if td.name == CLASS]
    if len(cu.types) != 1 or len(tds) != 1 or tds[0].kind != 'class':
        raise GenError(f'{path}: expected a single class {CLASS}')
    td = tds[0]
    if td.types or td.initializers or [str(e) for e in td.extends] != ['AionServerPacket']:
        raise _fail(cu, td.index, f'unexpected shape of class {CLASS}')
    factories = []
    others = []
    for m in td.methods:
        if 'static' not in m.modifiers:
            others.append(m)
            continue
        if m.kind != 'method' or set(m.modifiers) != {'public', 'static'} or str(m.return_type) not in FACTORY_RETURN_TYPES or m.type_params:
            raise _fail(cu, m.index, f'unexpected static member {m.name}: only public static factories returning {CLASS} are supported')
        if m.body is None or m.throws or m.annotations:
            raise _fail(cu, m.index, f'unsupported factory declaration {m.name}')
        f = Factory(m, javadoc_lines(cu, m.index, m.doc))
        classify(cu, f)
        factories.append(f)
    if not factories:
        raise _fail(cu, td.index, 'no factories found')
    # C++ overloads must stay distinct
    signatures = {}
    for f in factories:
        if f.kind == 'hand':
            continue
        key = (f.cpp_name, tuple(PARAM_TYPES[ty][0] for ty, _ in f.params))
        if key in signatures:
            raise _fail(cu, f.method.index, f'{f.java_signature()} and {signatures[key]} have the same C++ signature')
        signatures[key] = f.java_signature()
    for f in td.fields:
        if 'static' in f.modifiers:
            raise _fail(cu, f.index, f'unexpected static field {f.name}')
    return cu, factories, others


def doc_block(lines, indent=''):
    if not lines:
        return []
    safe = [line.replace('*/', '* /') for line in lines]
    if len(safe) == 1:
        return [f'{indent}/** {safe[0]} */']
    return [f'{indent}/**'] + [f'{indent} * {line}'.rstrip() for line in safe] + [f'{indent} */']


def report_lines(factories, others):
    total = len(factories)
    hand = [f for f in factories if f.kind == 'hand']
    generated = [f for f in factories if f.kind == 'generated']
    plain = [f for f in factories if f.kind == 'plain']
    lines = [f'{total} factories in Java: {total - len(hand)} generated ({len(plain)} plain, {len(generated)} with other bodies), '
             f'{len(hand)} to port by hand.',
             '',
             'To port by hand (not generated; declare and define them in the hand-written class):']
    for f in hand:
        lines.append(f'  {f.java_signature()}  [{"; ".join(f.notes)}]')
        lines.append(f'    {f.java_expr}')
    lines += ['', 'Generated from bodies that are not a plain new SM_SYSTEM_MESSAGE(id, <parameters in order>):']
    for f in generated:
        lines.append(f'  {f.java_signature()}  [{"; ".join(f.notes)}]')
        lines.append(f'    {f.java_expr}')
    members = sorted(set(m.name + ('()' if m.kind == 'method' else ' constructor') for m in others))
    lines += ['', f'Not generated (instance members, ported by hand): {", ".join(members)}']
    return lines


def render_header(factories, others):
    out = [HEADER_NOTE,
           f'// Source: game-server/{SYSMSG_JAVA}',
           '//',
           f'// Member block of class {CLASS}: #include it in a public section of the class body in the hand-written',
           f'// {OUT_PREFIX}.h (this file has no include guard). The definitions are in {os.path.basename(OUT_PREFIX)}.gen0.cpp to',
           f'// {os.path.basename(OUT_PREFIX)}.gen{SOURCE_COUNT - 1}.cpp. Contract with the hand-written class:',
           f'//   {CLASS}(int32_t msgId, std::vector<std::string> params);     Java: {CLASS}(int msgId, Object... params)',
           '//   static std::string toJavaString(int32_t / int64_t / int8_t / float);   Java: String.valueOf of int, long, byte, float',
           '//   <cstdint>, <string>, <string_view> and <vector> are included before this block.',
           '// String parameters are std::string_view (Java null is not representable; Java would send an empty string, or "null" inside a',
           '// concatenation). Unused parameters are unnamed.',
           '//',
           '// Report']
    out += [f'//   {line}'.rstrip() for line in report_lines(factories, others)]
    out.append('')
    for f in factories:
        if f.kind == 'hand':
            continue
        out += doc_block(f.doc)
        out.append(f'static {CLASS} {f.cpp_name}({f.cpp_params(False)});')
    out.append('')
    return '\n'.join(out)


def render_sources(factories):
    generated = [f for f in factories if f.kind != 'hand']
    per_file = -(-len(generated) // SOURCE_COUNT)
    outputs = {}
    for n in range(SOURCE_COUNT):
        part = generated[n * per_file:(n + 1) * per_file]
        out = [HEADER_NOTE,
               f'// Source: game-server/{SYSMSG_JAVA} (factories {n * per_file + 1} to {n * per_file + len(part)} of {len(generated)})',
               f'#include "aion/gameserver/{OUT_PREFIX}.h"',
               '',
               '#include <cstdint>',
               '#include <string>',
               '#include <string_view>',
               '#include <vector>',
               '',
               'namespace aion::gameserver::network::aion::serverpackets {',
               '']
        for f in part:
            out.append(f'{CLASS} {CLASS}::{f.cpp_name}({f.cpp_params(True)}) {{')
            args = ', '.join(f.args)
            out.append(f'\treturn {CLASS}({f.msg_id}, std::vector<std::string>{{{args}}});')
            out.append('}')
            out.append('')
        out += ['} // namespace aion::gameserver::network::aion::serverpackets', '']
        outputs[f'{OUT_PREFIX}.gen{n}.cpp'] = '\n'.join(out)
    return outputs


def generate(java_dir):
    """Returns ({output relpath: content}, summary dict)."""
    _, factories, others = parse(os.path.abspath(java_dir))
    outputs = {HEADER_OUT: render_header(factories, others)}
    outputs.update(render_sources(factories))
    param_counts = {}
    for f in factories:
        for ty, _ in f.params:
            param_counts[ty] = param_counts.get(ty, 0) + 1
    summary = {
        'factories': len(factories),
        'distinct_names': len({f.name for f in factories}),
        'plain': sum(1 for f in factories if f.kind == 'plain'),
        'generated_non_plain': sorted(f.java_signature() for f in factories if f.kind == 'generated'),
        'hand_ported': sorted(f.java_signature() for f in factories if f.kind == 'hand'),
        'parameter_types': dict(sorted(param_counts.items())),
    }
    return outputs, summary, report_lines(factories, others)


def write_outputs(outputs, out_dir, check):
    """Writes (or with check compares) the outputs; returns the relpaths that differ."""
    differ = []
    for rel, content in sorted(outputs.items()):
        path = os.path.join(out_dir, rel)
        old = None
        if os.path.isfile(path):
            with open(path, encoding='utf-8', newline='') as f:
                old = f.read()
        if old == content:
            continue
        differ.append(rel)
        if not check:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, 'w', encoding='utf-8', newline='\n') as f:
                f.write(content)
    return differ


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--java-dir', default=DEFAULT_JAVA_DIR, help='the Java game-server directory')
    ap.add_argument('--out-dir', default=DEFAULT_OUT_DIR, help='cpp/game-server/src/aion/gameserver')
    ap.add_argument('--check', action='store_true', help='exit 1 if a committed output is out of date')
    ap.add_argument('--report', action='store_true', help='print the report of hand-ported and non-plain factories')
    args = ap.parse_args(argv)
    try:
        outputs, summary, report = generate(args.java_dir)
    except (GenError, javasrc.JavaSyntaxError) as e:
        print(f'error: {e}', file=sys.stderr)
        return 2
    differ = write_outputs(outputs, args.out_dir, args.check)
    if args.report:
        print('\n'.join(report))
    else:
        for k, v in summary.items():
            print(f'{k}: {v}')
    for rel in differ:
        print(f'{"out of date" if args.check else "written"}: {rel}')
    return 1 if args.check and differ else 0


if __name__ == '__main__':
    sys.exit(main())
