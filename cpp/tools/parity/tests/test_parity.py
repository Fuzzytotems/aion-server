class Detection(unittest.TestCase):
    """each check fires on the mutation it exists for, and only the checks that should"""

    def mutated(self, old, new):
        self.assertIn(old, BASE_CPP)
        return checks(BASE_JAVA, BASE_CPP.replace(old, new, 1))

    def test_base_pair_is_at_parity(self):
        self.assertEqual(checks(BASE_JAVA, BASE_CPP), [])

    def test_changed_literal(self):
        self.assertEqual(self.mutated('sendQuestDialog(env, 1011)', 'sendQuestDialog(env, 1012)'), ['literals-multiset', 'literals-order'])

    def test_swapped_literals_only_break_the_order(self):
        self.assertEqual(self.mutated('defaultCloseDialog(env, 0, 1)', 'defaultCloseDialog(env, 1, 0)'), ['literals-order'])

    def test_dropped_call(self):
        self.assertEqual(self.mutated('\t\t\t\t\tplayQuestMovie(env, 15);\n', '\t\t\t\t\tsendPacket(env, 15);\n'),
                         ['calls-multiset', 'calls-order'])

    def test_reordered_calls_only_break_the_order(self):
        j = BASE_JAVA.replace('\t\t\t\t\tplayQuestMovie(env, 15);\n', '')
        c = BASE_CPP.replace('\t\t\t\t\tplayQuestMovie(env, 15);\n', '').replace('return defaultCloseDialog(env, 0, 1);',
                                                                              'return defaultCloseDialog(env, 0, 1) && playQuestMovie(env, 15);')
        j = j.replace('return defaultCloseDialog(env, 0, 1);', 'return playQuestMovie(env, 15) && defaultCloseDialog(env, 0, 1);')
        self.assertEqual(checks(j, c), ['literals-order', 'calls-order'])

    def test_flipped_operator(self):
        self.assertEqual(self.mutated('qs == nullptr ||', 'qs != nullptr ||'), ['operators-order'])

    def test_changed_constant(self):
        self.assertEqual(self.mutated('case SETPRO1:', 'case SETPRO2:'), ['constants-order'])
        self.assertEqual(self.mutated('QuestStatus::START', 'QuestStatus::REWARD'), ['constants-order'])

    def test_changed_companion(self):
        self.assertEqual(self.mutated('world::getId(WorldMapType::POETA)', 'world::getName(WorldMapType::POETA)'),
                         ['calls-multiset', 'calls-order', 'companions'])

    def test_changed_spawn_id(self):
        self.assertEqual(self.mutated('spawnForFiveMinutes(203558,', 'spawnForFiveMinutes(203559,'),
                         ['literals-multiset', 'literals-order', 'spawn-ids'])

    def test_swapped_constants_only_break_the_constant_order(self):
        c = BASE_CPP.replace('case QUEST_SELECT:', 'case @:').replace('case SETPRO1:', 'case QUEST_SELECT:').replace('case @:', 'case SETPRO1:')
        self.assertEqual(checks(BASE_JAVA, c), ['constants-order'])

    def test_swapped_operators_only_break_the_operator_order(self):
        self.assertEqual(checks(java('\t\treturn a < b && c > d;'), cpp('\t\treturn a > b && c < d;')), ['operators-order'])

    def test_the_spawn_analyzer_reads_comments_sp_and_ternaries(self):
        # QuestSpawnAnalyzer.java:101 runs over the raw file: a commented-out spawn counts, and so do sp( and both ids of a ternary
        body = '\t\t// spawn(216239, player);\n\t\tsp(player.isMentor() ? 204001 : 204002, player);\n\t\treturn true;'
        j = java(body)
        self.assertEqual(parity.spawn_analyzer_ids(j), {216239, 204001, 204002})
        c = cpp('\t\tsp(player->isMentor() ? 204001 : 204002, *player);\n\t\treturn true;')
        self.assertEqual(checks(j, c), ['spawn-analyzer'])
        self.assertEqual(checks(j, cpp('\t\t// spawn(216239, player);\n\t\tsp(player->isMentor() ? 204001 : 204002, *player);\n\t\treturn true;')),
                         [])


class Commands(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix='parity'))
        self.jd, self.cd = self.tmp / 'java', self.tmp / 'cpp'
        for rel, j, c in (('a/_1Good.java', BASE_JAVA, BASE_CPP), ('b/_2Bad.java', BASE_JAVA, BASE_CPP.replace('1011', '1012')),
                          ('c/_3Missing.java', BASE_JAVA, None)):
            (self.jd / rel).parent.mkdir(parents=True, exist_ok=True)
            (self.jd / rel).write_text(j, encoding='utf-8')
            if c is not None:
                (self.cd / rel).parent.mkdir(parents=True, exist_ok=True)
                (self.cd / rel.replace('.java', '.cpp')).write_text(c, encoding='utf-8')

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def run_main(self, argv):
        with contextlib.redirect_stdout(io.StringIO()) as out, contextlib.redirect_stderr(io.StringIO()):
            code = parity.main(argv)
        return code, out.getvalue()

    def test_tree_report(self):
        rep = parity.tree_report(parity.compare_tree(self.jd, self.cd))
        self.assertEqual((rep['javaFiles'], rep['compared'], rep['mismatchedFiles'], rep['missingCpp']), (3, 2, 1, 1))
        self.assertEqual(list(rep['files']), ['b/_2Bad.java'])
        self.assertEqual(rep['mismatchesByCheck']['literals-order'], 1)
        self.assertEqual(rep['mismatchesByCheck']['calls-order'], 0)

    def test_exit_codes(self):
        out = self.tmp / 'r.json'
        self.assertEqual(self.run_main(['tree', '--java-dir', str(self.jd), '--cpp-dir', str(self.cd), '--json', str(out)])[0], 1)
        self.assertEqual(json.loads(out.read_text(encoding='utf-8'))['mismatchedFiles'], 1)
        self.assertEqual(self.run_main(['tree', '--java-dir', str(self.jd), '--cpp-dir', str(self.cd), '--only', 'a/_1Good.java'])[0], 0)
        self.assertEqual(self.run_main(['tree', '--java-dir', str(self.jd), '--cpp-dir', str(self.cd), '--only', '_1Good', '_3Missing'])[0], 0)
        self.assertEqual(self.run_main(['tree', '--java-dir', str(self.jd), '--cpp-dir', str(self.cd), '--only', '_1Good', '_3Missing',
                                        '--require-all'])[0], 1)
        code, text = self.run_main(['pair', str(self.jd / 'a/_1Good.java'), str(self.cd / 'a/_1Good.cpp')])
        self.assertEqual((code, text.strip()), (0, 'parity: OK'))
        self.assertEqual(self.run_main(['pair', str(self.jd / 'b/_2Bad.java'), str(self.cd / 'b/_2Bad.cpp')])[0], 1)
        (self.tmp / 'x.cpp').write_text('namespace x {}\n', encoding='utf-8')
        self.assertEqual(self.run_main(['pair', str(self.jd / 'a/_1Good.java'), str(self.tmp / 'x.cpp')])[0], 2)   # no class

    def test_spawn_analyzer_over_directories(self):
        # QuestSpawnAnalyzer.loadNpcIdsSpawnedByHandlers: the pattern over every file of the directories (subdirectories included) whose name
        # ends with a suffix (.java by default, the analyzer's filter); the union of the ids, ascending, after a count line
        files = {'s/one/X.java': '\t// spawn(216239, player);\n\tsp(a ? 204001 : 204002, player);\n',
                 's/one/deep/Y.cpp': '\tspawn(700001, *player);\n', 's/one/Z.h': 'sp(700002);\n', 's/one/N.txt': 'spawn(999999);\n',
                 's/two/W.java': '\tspawn(204001);\n\tspawn(npcId, 205000);\n\trespawn(205001);\n'}
        for rel, text in files.items():
            (self.tmp / rel).parent.mkdir(parents=True, exist_ok=True)
            (self.tmp / rel).write_text(text, encoding='utf-8')
        one, two = str(self.tmp / 's/one'), str(self.tmp / 's/two')
        self.assertEqual(parity.spawn_analyzer_dirs([one, two]), (2, {216239, 204001, 204002}))
        self.assertEqual(parity.spawn_analyzer_dirs([one], ('.cpp', '.h')), (2, {700001, 700002}))
        code, text = self.run_main(['spawn-analyzer', one, two])
        self.assertEqual((code, text.splitlines()), (0, ['# 2 files, 3 npc ids', '204001', '204002', '216239']))
        code, text = self.run_main(['spawn-analyzer', '--suffix', '.cpp', '--suffix', '.h', one])
        self.assertEqual((code, text.splitlines()), (0, ['# 2 files, 2 npc ids', '700001', '700002']))
        self.assertEqual(self.run_main(['spawn-analyzer', str(self.tmp / 's/missing')])[0], 2)


